    S, ...
    requiredFields, ...
    structureName)

for fieldIndex = 1:numel(requiredFields)

    fieldName = ...
        requiredFields{fieldIndex};

    if ~isfield(S, fieldName)

        error( ...
            'Cyclo:MissingDeviceInputField', ...
            '%s is missing required field %s.', ...
            structureName, ...
            fieldName);

    end

end

end


function validateDeviceCurrents( ...
    Device, ...
    State, ...
    Current, ...
    expectedSamples, ...
    expectedGroups)
%VALIDATEDEVICECURRENTS
% Validate the explicit ABB topology consisting of:
%
%   6 thyristors in the positive converter bridge
%   6 thyristors in the negative converter bridge
%
% for every motor output phase and converter group.

%% =========================================================
% 1. Main physical-device array dimensions
%% =========================================================

if size(Device.thyristorState, 1) ~= expectedSamples

    error( ...
        'Cyclo:ThyristorStateLengthMismatch', ...
        ['Thyristor-state sample count is incorrect. ', ...
         'Expected %d samples but obtained %d.'], ...
        expectedSamples, ...
        size(Device.thyristorState, 1));

end

if size(Device.thyristorState, 2) ~= 12

    error( ...
        'Cyclo:ThyristorStateCountMismatch', ...
        ['Twelve physical thyristor states are required ', ...
         'per output phase and converter group. ', ...
         'The current array contains %d device states.'], ...
        size(Device.thyristorState, 2));

end

if size(Device.thyristorState, 3) ~= expectedGroups

    error( ...
        'Cyclo:ThyristorGroupCountMismatch', ...
        ['Expected %d converter groups but obtained %d.'], ...
        expectedGroups, ...
        size(Device.thyristorState, 3));

end

if size(Device.thyristorState, 4) ~= 3

    error( ...
        'Cyclo:ThyristorOutputPhaseCountMismatch', ...
        ['Three motor output phases are required. ', ...
         'The current array contains %d output phases.'], ...
        size(Device.thyristorState, 4));

end

%% =========================================================
% 2. Positive and negative bridge dimensions
%% =========================================================
%
% Each positive and negative converter bridge must contain:
%
%   T1, T3, T5, T4, T6, T2

if size(Device.positiveBridgeState, 1) ~= expectedSamples || ...
        size(Device.positiveBridgeState, 2) ~= 6 || ...
        size(Device.positiveBridgeState, 3) ~= expectedGroups || ...
        size(Device.positiveBridgeState, 4) ~= 3

    error( ...
        'Cyclo:PositiveBridgeDimensionMismatch', ...
        ['Device.positiveBridgeState must have dimensions ', ...
         '%d x 6 x %d x 3.'], ...
        expectedSamples, ...
        expectedGroups);

end

if size(Device.negativeBridgeState, 1) ~= expectedSamples || ...
        size(Device.negativeBridgeState, 2) ~= 6 || ...
        size(Device.negativeBridgeState, 3) ~= expectedGroups || ...
        size(Device.negativeBridgeState, 4) ~= 3

    error( ...
        'Cyclo:NegativeBridgeDimensionMismatch', ...
        ['Device.negativeBridgeState must have dimensions ', ...
         '%d x 6 x %d x 3.'], ...
        expectedSamples, ...
        expectedGroups);

end

%% =========================================================
% 3. Upper and lower selection-array dimensions
%% =========================================================

selectionFields = { ...
    'positiveBridgeUpperState', ...
    'positiveBridgeLowerState', ...
    'negativeBridgeUpperState', ...
    'negativeBridgeLowerState'};

for fieldIndex = 1:numel(selectionFields)

    fieldName = selectionFields{fieldIndex};

    if size(Device.(fieldName), 1) ~= expectedSamples || ...
            size(Device.(fieldName), 2) ~= 3 || ...
            size(Device.(fieldName), 3) ~= expectedGroups || ...
            size(Device.(fieldName), 4) ~= 3

        error( ...
            'Cyclo:BridgeSelectionDimensionMismatch', ...
            ['Device.%s must have dimensions ', ...
             '%d x 3 x %d x 3.'], ...
            fieldName, ...
            expectedSamples, ...
            expectedGroups);

    end

end

%% =========================================================
% 4. Finite-current checks
%% =========================================================

numericFields = { ...
    'thyristorCurrentSigned', ...
    'thyristorCurrent', ...
    'representativeSourceCurrent', ...
    'representativeGroupCurrentA', ...
    'representativeGroupCurrentB', ...
    'representativeGroupCurrentC', ...
    'representativeGroupSourceCurrentRms', ...
    'representativeGroupSourceCurrentPeak', ...
    'sourceCurrentContribution', ...
    'groupSourceCurrent', ...
    'totalSourceCurrentA', ...
    'totalSourceCurrentB', ...
    'totalSourceCurrentC'};

for fieldIndex = 1:numel(numericFields)

    fieldName = numericFields{fieldIndex};

    if any(~isfinite(Device.(fieldName)(:)))

        error( ...
            'Cyclo:NonFiniteDeviceCurrent', ...
            'Device.%s contains non-finite values.', ...
            fieldName);

    end

end

%% =========================================================
% 5. Positive and negative bridge interlock
%% =========================================================
%
% Reduce each six-device bridge to one active/inactive state.
%
% The result dimensions are:
%
%   sample x 1 x group x output phase

positiveBridgeActive = ...
    any( ...
        Device.positiveBridgeState, ...
        2);

negativeBridgeActive = ...
    any( ...
        Device.negativeBridgeState, ...
        2);

simultaneousBridgeConduction = ...
    positiveBridgeActive ...
    & negativeBridgeActive;

if any(simultaneousBridgeConduction(:))

    error( ...
        'Cyclo:SimultaneousBridgeConduction', ...
        ['Positive and negative converter bridges conduct ', ...
         'simultaneously.']);

end

%% =========================================================
% 6. Count conducting devices in each physical bridge
%% =========================================================
%
% A conducting six-pulse bridge must contain:
%
%   one conducting upper thyristor
%   one conducting lower thyristor
%
% Therefore, exactly two thyristors conduct in the selected
% positive or negative bridge.

positiveDeviceCount = ...
    sum( ...
        Device.positiveBridgeState, ...
        2);

negativeDeviceCount = ...
    sum( ...
        Device.negativeBridgeState, ...
        2);

for outputPhase = 1:3

    positiveCurrentMask = ...
        Device.positivePolarity(:, outputPhase);

    negativeCurrentMask = ...
        Device.negativePolarity(:, outputPhase);

    zeroCurrentMask = ...
        Device.zeroPolarity(:, outputPhase);

    for groupNumber = 1:expectedGroups

        positiveCount = ...
            reshape( ...
                positiveDeviceCount( ...
                    :, ...
                    1, ...
                    groupNumber, ...
                    outputPhase), ...
                expectedSamples, ...
                1);

        negativeCount = ...
            reshape( ...
                negativeDeviceCount( ...
                    :, ...
                    1, ...
                    groupNumber, ...
                    outputPhase), ...
                expectedSamples, ...
                1);

        %% Positive motor current

        if any(positiveCount(positiveCurrentMask) ~= 2)

            error( ...
                'Cyclo:InvalidPositiveBridgeDeviceCount', ...
                ['Exactly two positive-bridge thyristors ', ...
                 'must conduct while motor current is positive.']);

        end

        if any(negativeCount(positiveCurrentMask) ~= 0)

            error( ...
                'Cyclo:NegativeBridgeActiveWithPositiveCurrent', ...
                ['The negative converter bridge must be ', ...
                 'blocked while motor current is positive.']);

        end

        %% Negative motor current

        if any(negativeCount(negativeCurrentMask) ~= 2)

            error( ...
                'Cyclo:InvalidNegativeBridgeDeviceCount', ...
                ['Exactly two negative-bridge thyristors ', ...
                 'must conduct while motor current is negative.']);

        end

        if any(positiveCount(negativeCurrentMask) ~= 0)

            error( ...
                'Cyclo:PositiveBridgeActiveWithNegativeCurrent', ...
                ['The positive converter bridge must be ', ...
                 'blocked while motor current is negative.']);

        end

        %% Zero motor current

        if any(positiveCount(zeroCurrentMask) ~= 0) || ...
                any(negativeCount(zeroCurrentMask) ~= 0)

            error( ...
                'Cyclo:BridgeActiveAtZeroCurrent', ...
                ['Both converter bridges must be blocked ', ...
                 'while motor current is zero.']);

        end

    end

end

%% =========================================================
% 7. Verify one upper and one lower device
%% =========================================================

positiveUpperCount = ...
    sum( ...
        Device.positiveBridgeUpperState, ...
        2);

positiveLowerCount = ...
    sum( ...
        Device.positiveBridgeLowerState, ...
        2);

negativeUpperCount = ...
    sum( ...
        Device.negativeBridgeUpperState, ...
        2);

negativeLowerCount = ...
    sum( ...
        Device.negativeBridgeLowerState, ...
        2);

for outputPhase = 1:3

    positiveCurrentMask = ...
        Device.positivePolarity(:, outputPhase);

    negativeCurrentMask = ...
        Device.negativePolarity(:, outputPhase);

    zeroCurrentMask = ...
        Device.zeroPolarity(:, outputPhase);

    for groupNumber = 1:expectedGroups

        positiveUpper = ...
            reshape( ...
                positiveUpperCount( ...
                    :, 1, groupNumber, outputPhase), ...
                expectedSamples, ...
                1);

        positiveLower = ...
            reshape( ...
                positiveLowerCount( ...
                    :, 1, groupNumber, outputPhase), ...
                expectedSamples, ...
                1);

        negativeUpper = ...
            reshape( ...
                negativeUpperCount( ...
                    :, 1, groupNumber, outputPhase), ...
                expectedSamples, ...
                1);

        negativeLower = ...
            reshape( ...
                negativeLowerCount( ...
                    :, 1, groupNumber, outputPhase), ...
                expectedSamples, ...
                1);

        %% Positive bridge arm selection

        if any(positiveUpper(positiveCurrentMask) ~= 1) || ...
                any(positiveLower(positiveCurrentMask) ~= 1)

            error( ...
                'Cyclo:InvalidPositiveBridgeArmSelection', ...
                ['The positive bridge must select exactly ', ...
                 'one upper and one lower thyristor.']);

        end

        %% Negative bridge arm selection

        if any(negativeUpper(negativeCurrentMask) ~= 1) || ...
                any(negativeLower(negativeCurrentMask) ~= 1)

            error( ...
                'Cyclo:InvalidNegativeBridgeArmSelection', ...
                ['The negative bridge must select exactly ', ...
                 'one upper and one lower thyristor.']);

        end

        %% Inactive bridge checks

        if any(positiveUpper(~positiveCurrentMask) ~= 0) || ...
                any(positiveLower(~positiveCurrentMask) ~= 0)

            error( ...
                'Cyclo:UnexpectedPositiveBridgeArmSelection', ...
                ['The positive bridge arm states must be ', ...
                 'zero when positive motor current is absent.']);

        end

        if any(negativeUpper(~negativeCurrentMask) ~= 0) || ...
                any(negativeLower(~negativeCurrentMask) ~= 0)

            error( ...
                'Cyclo:UnexpectedNegativeBridgeArmSelection', ...
                ['The negative bridge arm states must be ', ...
                 'zero when negative motor current is absent.']);

        end

        %% Explicit zero-current check

        if any(positiveUpper(zeroCurrentMask) ~= 0) || ...
                any(positiveLower(zeroCurrentMask) ~= 0) || ...
                any(negativeUpper(zeroCurrentMask) ~= 0) || ...
                any(negativeLower(zeroCurrentMask) ~= 0)

            error( ...
                'Cyclo:BridgeArmActiveAtZeroCurrent', ...
                ['All upper and lower bridge selections must ', ...
                 'be zero while motor current is zero.']);

        end

    end

end

%% =========================================================
% 8. Thyristor-state and current consistency
%% =========================================================

inactiveCurrent = ...
    Device.thyristorCurrent( ...
        ~Device.thyristorState);

if any(inactiveCurrent ~= 0)

    error( ...
        'Cyclo:InactiveThyristorCurrent', ...
        'A blocked thyristor has nonzero current.');

end

if any(Device.thyristorCurrent(:) < 0)

    error( ...
        'Cyclo:NegativeThyristorMagnitude', ...
        'A thyristor current magnitude cannot be negative.');

end

%% Verify active-device current equals motor-current magnitude

motorCurrent = [ ...
    Current.iu(:), ...
    Current.iv(:), ...
    Current.iw(:)];
if any(~isfinite(motorCurrent(:)))

    error( ...
        'Cyclo:NonFiniteMotorCurrentInput', ...
        ['The input motor-current waveforms contain ', ...
         'non-finite values.']);

end
for outputPhase = 1:3

    expectedMagnitude = ...
        abs(motorCurrent(:, outputPhase));

    for groupNumber = 1:expectedGroups

        activeDeviceCurrentSum = ...
            sum( ...
                Device.thyristorCurrent( ...
                    :, ...
                    :, ...
                    groupNumber, ...
                    outputPhase), ...
                2);

        activeDeviceCurrentSum = ...
            reshape( ...
                activeDeviceCurrentSum, ...
                expectedSamples, ...
                1);

        %% Two thyristors carry the full motor phase current

        expectedDeviceCurrentSum = ...
            2 ...
            * expectedMagnitude;

        currentTolerance = ...
            1e-9 ...
            * max( ...
                1, ...
                max(expectedDeviceCurrentSum));

        if any( ...
                abs( ...
                    activeDeviceCurrentSum ...
                    - expectedDeviceCurrentSum) ...
                > currentTolerance)

            error( ...
                'Cyclo:ActiveThyristorCurrentMismatch', ...
                ['The sum of active thyristor currents must ', ...
                 'equal twice the motor-current magnitude.']);

        end

    end

end

%% =========================================================
% 9. Motor-current and source-state consistency
%% =========================================================

if numel(Current.iu) ~= expectedSamples || ...
        numel(Current.iv) ~= expectedSamples || ...
        numel(Current.iw) ~= expectedSamples

    error( ...
        'Cyclo:DeviceMotorCurrentLengthMismatch', ...
        ['Motor currents and device arrays must have ', ...
         'identical sample counts.']);

end

%% =========================================================
% Phase-specific source-state consistency
%% =========================================================
%
% Required dimensions:
%
%   sample x sourcePhase x converterGroup x outputPhase
%
% sourcePhase:
%   1 = A
%   2 = B
%   3 = C
%
% outputPhase:
%   1 = U
%   2 = V
%   3 = W

if size(State.positive,1) ~= expectedSamples || ...
        size(State.negative,1) ~= expectedSamples || ...
        size(State.positive,2) ~= 3 || ...
        size(State.negative,2) ~= 3 || ...
        size(State.positive,3) ~= expectedGroups || ...
        size(State.negative,3) ~= expectedGroups || ...
        size(State.positive,4) ~= 3 || ...
        size(State.negative,4) ~= 3

    error( ...
        'Cyclo:DeviceSourceStateDimensionMismatch', ...
        ['Source states must have dimensions ', ...
         'samples x 3 x groups x 3 output phases.']);

end

if size(State.positive, 2) ~= 3 || ...
        size(State.negative, 2) ~= 3

    error( ...
        'Cyclo:DeviceSourceStatePhaseMismatch', ...
        'Three converter source phases are required.');

end

if size(State.positive, 3) ~= expectedGroups || ...
        size(State.negative, 3) ~= expectedGroups

    error( ...
        'Cyclo:DeviceSourceStateGroupMismatch', ...
        'Source-state converter-group count is incorrect.');

end

%% =========================================================
% 10. Physical ABB topology count
%% =========================================================

if ~isfield(Device, 'totalPhysicalThyristors') || ...
        ~isfield(Device, 'expectedPhysicalThyristors')

    error( ...
        'Cyclo:MissingPhysicalTopologyMetadata', ...
        ['Physical thyristor-count metadata is missing ', ...
         'from the Device structure.']);

end

if Device.totalPhysicalThyristors ~= ...
        Device.expectedPhysicalThyristors

    error( ...
        'Cyclo:ValidatedThyristorCountMismatch', ...
        ['The modeled physical thyristor count does not ', ...
         'match the ABB converter topology.']);

end

