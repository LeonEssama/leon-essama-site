    'Not reconstructed';

Device.sourceCurrentStatus = ...
    'Representative branch only';

%% Rejected U+V+W repeated-state aggregation

Device.aggregatedRepeatedStateCurrentStatus = ...
    'Invalid for transformer-current validation';

Device.aggregatedRepeatedStateCurrentNote = ...
