end

if numel(widthFractions) ~= ...
        numberOfColumns

    error( ...
        'Cyclo:InvalidWordTableWidths', ...
        ['The number of table-width fractions does not ', ...
         'match the number of columns.']);

end

if abs(sum(widthFractions) - 1) > 1e-9

    error( ...
        'Cyclo:InvalidWordTableWidthSum', ...
        'The table-width fractions must sum to one.');

end

tableObject = ...
    Table();

tableObject.Width = ...
    '100%';

tableObject.Border = ...
    'solid';

tableObject.BorderWidth = ...
    '0.5pt';

tableObject.ColSep = ...
    'solid';

tableObject.RowSep = ...
    'solid';

for rowIndex = 1:numberOfRows

    tableRow = ...
        TableRow();

    for columnIndex = 1:numberOfColumns

        tableEntry = ...
            TableEntry();

        tableEntry.Style = { ...
            OuterMargin( ...
                '3pt', ...
                '3pt', ...
                '3pt', ...
                '3pt')};

        cellParagraph = ...
            Paragraph();

        cellValue = ...
            formatCellValue( ...
                cellData{rowIndex,columnIndex});

        append( ...
            cellParagraph, ...
            Text(cellValue));

        if rowIndex == 1

            cellParagraph.Style = ...
                styles.TableHeader;

            tableEntry.Style = [ ...
                tableEntry.Style, ...
                {BackgroundColor('#1F4E79')}];

        elseif columnIndex == 1

            cellParagraph.Style = ...
                styles.TableDescription;

            tableEntry.Style = [ ...
                tableEntry.Style, ...
                {BackgroundColor('#D9EAF7')}];

        else

            cellParagraph.Style = ...
                styles.TableValue;

        end

        append( ...
            tableEntry, ...
            cellParagraph);

        append( ...
            tableRow, ...
            tableEntry);

    end

    append( ...
        tableObject, ...
        tableRow);

end

append( ...
    document, ...
    tableObject);

tableSpacer = ...
    Paragraph(' ');

append( ...
    document, ...
    tableSpacer);

end
function appendReportFigure( ...
    document, ...
    figureFolder, ...
    figureFileName, ...
    captionText, ...
    noteText, ...
    imageWidth)

import mlreportgen.dom.*
%% Use a default width when no width is provided

if nargin < 6 || ...
        strlength(string(imageWidth)) == 0

    imageWidth = ...
        "130mm";

end
%% Validate source image

figurePath = ...
    fullfile( ...
        figureFolder, ...
        string(figureFileName));

if ~isfile(figurePath)

    error( ...
        'Cyclo:MissingWordReportFigure', ...
        'The report figure does not exist: %s', ...
        figurePath);

end

figureInformation = ...
    dir(figurePath);

if figureInformation.bytes <= 0

    error( ...
        'Cyclo:EmptyWordReportFigure', ...
        'The report figure is empty: %s', ...
        figurePath);

end

%% Insert figure

%% Read the original PNG dimensions

imageInformation = ...
    imfinfo( ...
        char(figurePath));

sourceWidthPixels = ...
    double(imageInformation.Width);

sourceHeightPixels = ...
    double(imageInformation.Height);

if sourceWidthPixels <= 0 || ...
        sourceHeightPixels <= 0

    error( ...
        'Cyclo:InvalidWordReportFigureDimensions', ...
        'The report figure has invalid pixel dimensions.');

end

%% Convert requested Word width from millimetres

imageWidthText = ...
    string(imageWidth);

if ~endsWith( ...
        lower(imageWidthText), ...
        "mm")

    error( ...
        'Cyclo:InvalidWordImageWidthUnit', ...
        'The Word image width must be specified in millimetres.');

end

imageWidthMillimetres = ...
    str2double( ...
        erase( ...
            lower(imageWidthText), ...
            "mm"));

if ~isfinite(imageWidthMillimetres) || ...
        imageWidthMillimetres <= 0

    error( ...
        'Cyclo:InvalidWordImageWidth', ...
        'The Word image width must be finite and positive.');

end

%% Preserve the original image aspect ratio

aspectRatio = ...
    sourceHeightPixels ...
    / sourceWidthPixels;

imageHeightMillimetres = ...
    imageWidthMillimetres ...
    * aspectRatio;

%% Insert image with explicit width and height

imageObject = ...
    Image( ...
        char(figurePath));

imageObject.Width = ...
    sprintf( ...
        '%.2fmm', ...
        imageWidthMillimetres);

imageObject.Height = ...
    sprintf( ...
        '%.2fmm', ...
        imageHeightMillimetres);
fprintf( ...
    ['Word figure: %s\n', ...
     '  Source: %d x %d pixels\n', ...
     '  Display: %.2f x %.2f mm\n'], ...
    char(string(figureFileName)), ...
    sourceWidthPixels, ...
    sourceHeightPixels, ...
    imageWidthMillimetres, ...
    imageHeightMillimetres);

imageParagraph = ...
    Paragraph();

imageParagraph.Style = { ...
    HAlign('center')};

append( ...
    imageParagraph, ...
    imageObject);

append( ...
    document, ...
    imageParagraph);

%% Insert caption

captionParagraph = ...
    Paragraph();

captionParagraph.Style = { ...
    FontFamily('Arial'), ...
    FontSize('9pt'), ...
    Bold(true), ...
    HAlign('center')};

append( ...
    captionParagraph, ...
    Text( ...
        string(captionText)));

append( ...
    document, ...
    captionParagraph);

%% Insert optional note

if strlength(string(noteText)) > 0

    noteParagraph = ...
        Paragraph();

    noteParagraph.Style = { ...
        FontFamily('Arial'), ...
        FontSize('8pt'), ...
        Italic(true), ...
        Color('#666666'), ...
        HAlign('center')};

    append( ...
        noteParagraph, ...
        Text( ...
            string(noteText)));

    append( ...
        document, ...
        noteParagraph);

end

%% Add spacing after figure

append( ...
    document, ...
    Paragraph(' '));

end

function textValue = formatCellValue(value)

if isempty(value)

    textValue = ...
        "";

elseif isnumeric(value)

    if isscalar(value)

        if isnan(value)

            textValue = ...
                "";

        elseif abs(value) >= 1000

            textValue = ...
                sprintf( ...
                    '%.0f', ...
                    value);

        elseif abs(value) >= 100

            textValue = ...
                sprintf( ...
                    '%.1f', ...
                    value);

        elseif abs(value) >= 1

            textValue = ...
                sprintf( ...
                    '%.3f', ...
                    value);

        else

            textValue = ...
                sprintf( ...
                    '%.4f', ...
                    value);

        end

    else

        textValue = ...
            string(value);

    end

elseif islogical(value)

    if value

        textValue = ...
            "PASS";

    else

        textValue = ...
            "FAIL";

    end

else

    textValue = ...
        string(value);

end

end


function value = findTableValue(tableData, parameterName)

value = ...
    "";

for rowIndex = 2:size(tableData,1)

    rowName = ...
        string( ...
            tableData{rowIndex,1});

    if strcmpi( ...
            strtrim(rowName), ...
            strtrim(parameterName))

        value = ...
            string( ...
                tableData{rowIndex,2});

        return

    end

end

end
function value = optionalDisplayText( ...
    sourceValue, ...
    defaultValue)
%OPTIONALDISPLAYTEXT
% Return a default display value when report metadata is empty.

sourceText = ...
    strtrim( ...
        string(sourceValue));

if strlength(sourceText) == 0

    value = ...
        string(defaultValue);

else

    value = ...
        sourceText;

end

end
