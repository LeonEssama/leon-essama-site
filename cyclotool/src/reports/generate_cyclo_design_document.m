function appendHeading( ...
    document, ...
    headingText, ...
    headingStyle, ...
    headingLevel)
%APPENDHEADING Add a real Word heading to the document.
%
% headingLevel:
%   1 = main section
%   2 = subsection

import mlreportgen.dom.*

%% Use Heading 1 when no level is provided

if nargin < 4

    headingLevel = ...
        1;

end

%% Validate heading level

if ~isnumeric(headingLevel) || ...
        ~isscalar(headingLevel) || ...
        ~isfinite(headingLevel) || ...
        ~ismember(headingLevel, [1, 2])

    error( ...
        'Cyclo:InvalidWordHeadingLevel', ...
        'The Word heading level must be numeric 1 or 2.');

end

%% Create a real Word heading

heading = ...
    Heading( ...
        headingLevel, ...
        char(string(headingText)));

heading.Style = ...
    headingStyle;

append( ...
    document, ...
    heading);

end


