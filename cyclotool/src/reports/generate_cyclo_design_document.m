function documentName = createDocumentName(Metadata)

documentNumber = ...
    sanitizeFileName( ...
        string(Metadata.DocumentNumber));

revision = ...
    sanitizeFileName( ...
        string(Metadata.Revision));

if strlength(documentNumber) == 0

    documentNumber = ...
        "CycloTool_Design_Data";

end

if strlength(revision) == 0

    revision = ...
        "A";

end

documentName = ...
    documentNumber ...
    + "_Rev" ...
    + revision;

end


function value = sanitizeFileName(value)

value = ...
    string(value);

invalidCharacters = ...
    ["<", ">", ":", """", "/", "\", "|", "?", "*"];

for characterIndex = 1:numel(invalidCharacters)

    value = ...
        replace( ...
            value, ...
            invalidCharacters(characterIndex), ...
            "_");

end

value = ...
    strip(value);

end


