function Report = build_cyclo_design_report_model(DesignData)
%BUILD_CYCLO_DESIGN_REPORT_MODEL
% Convert a consolidated CycloTool DesignData structure into
% tables and figure definitions for Design Data generation.
%
% This function performs no engineering calculations. It only
% organizes previously calculated and validated CycloTool data.
%
% Input:
%   DesignData
%       Consolidated structure created by:
%       build_cyclo_design_data
%
% Output:
%   Report
%       Formatted report tables, figure definitions, metadata,
%       status information, and model limitations.

arguments
    DesignData (1,1) struct
end

%% =========================================================
% Validate required top-level sections
%% =========================================================

requiredSections = { ...
    'Document', ...
    'Project', ...
    'Input', ...
    'Dimensioning', ...
    'OperatingPoint', ...
    'Harmonics', ...
    'Characteristic', ...
    'FiringAngle', ...
    'Excitation', ...
    'Protection', ...
    'DetailedSimulation', ...
    'Supply', ...
    'Converter', ...
    'Motor', ...
    'Simulation', ...
    'Validation'};

for sectionIndex = 1:numel(requiredSections)

    sectionName = ...
        requiredSections{sectionIndex};

    if ~isfield(DesignData, sectionName)

        error( ...
            'Cyclo:MissingDesignReportSection', ...
            'DesignData is missing required section %s.', ...
            sectionName);

    end

end

