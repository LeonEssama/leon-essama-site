function value = getText(S, fieldName)

if isfield(S, fieldName) && ...
        strlength(string(S.(fieldName))) > 0

    value = ...
        string(S.(fieldName));

else

    value = ...
        "";

end

end


function value = getNumeric(S, fieldName)

if isfield(S, fieldName) && ...
        ~isempty(S.(fieldName))

    value = ...
        S.(fieldName);

else

    value = ...
        NaN;

end

end

function value = statusText(condition)
%STATUSTEXT Convert a logical or numeric status to report text.

if ~isscalar(condition)
    error( ...
        'Cyclo:InvalidReportStatus', ...
        'The report status must be a scalar value.');
end
if islogical(condition)
    statusIsTrue = ...
        condition;
elseif isnumeric(condition) && ...
        isfinite(condition) && ...
        ismember(condition, [0, 1])
    statusIsTrue = ...
        logical(condition);
else
    error( ...
        'Cyclo:InvalidReportStatus', ...
        ['The report status must be a logical scalar ', ...
         'or numeric 0 or 1.']);
end
if statusIsTrue
    value = ...
        "PASS";
else
    value = ...
        "REVIEW REQUIRED";
end
end

function validateReportModel(Report)

requiredTables = { ...
    'DocumentIdentification', ...
    'ProjectIdentification', ...
    'Supply', ...
    'Converter', ...
    'ConverterCurrents', ...
    'Thermal', ...
    'Motor', ...
    'MotorCurrents', ...
    'OperatingPoint', ...
    'MotorCharacteristic', ...
    'FiringAngle', ...
    'Harmonics', ...
    'Excitation', ...
    'Protection', ...
    'ProtectiveSettings', ...
    'RepresentativeGroupCurrents', ...
    'DetailedSimulation', ...
    'ValidationStatus'};

for tableIndex = 1:numel(requiredTables)

    tableName = ...
        requiredTables{tableIndex};

    if ~isfield(Report, tableName) || ...
            isempty(Report.(tableName))

        error( ...
            'Cyclo:MissingDesignReportTable', ...
            'The report model is missing table %s.', ...
            tableName);

    end

end

if ~isfield(Report, 'Metadata') || ...
        isempty(fieldnames(Report.Metadata))

    error( ...
        'Cyclo:MissingDesignReportMetadata', ...
        'The report model contains no metadata.');

end

if ~isfield(Report, 'Figures') || ...
        isempty(fieldnames(Report.Figures))

    error( ...
        'Cyclo:MissingDesignReportFigures', ...
        'The report model contains no figure definitions.');

end

figureNames = ...
    fieldnames(Report.Figures);

for figureIndex = 1:numel(figureNames)

    figureName = ...
        figureNames{figureIndex};

    figureDefinition = ...
        Report.Figures.(figureName);

    if ~isfield(figureDefinition, 'Title') || ...
            ~isfield(figureDefinition, 'Enabled') || ...
            ~isfield(figureDefinition, 'FileName')

        error( ...
            'Cyclo:InvalidDesignReportFigure', ...
            'Figure definition %s is incomplete.', ...
            figureName);

    end

end

if isempty(Report.ModelLimitations)

    error( ...
        'Cyclo:MissingDesignReportLimitations', ...
        'The report model contains no model limitations.');

end

end