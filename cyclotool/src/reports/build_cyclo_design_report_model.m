    'Group', ...
    'Phase A RMS [A]', ...
    'Phase B RMS [A]', ...
    'Phase C RMS [A]', ...
    'Mean RMS [A]', ...
    'I1S Ratio [-]', ...
    'I1S Error [%]'};

for groupIndex = 1:numberOfGroups

    groupPhaseRms = ...
        representativeRms(:,groupIndex);

    groupMeanRms = ...
        mean(groupPhaseRms);

    currentRatio = ...
        groupMeanRms ...
        / DesignData.Converter.secondaryCurrentA;

    currentErrorPercent = ...
        100 ...
        * ( ...
        groupMeanRms ...
        - DesignData.Converter.secondaryCurrentA) ...
        / DesignData.Converter.secondaryCurrentA;

    Report.RepresentativeGroupCurrents(groupIndex+1,:) = { ...
        groupIndex, ...
        groupPhaseRms(1), ...
        groupPhaseRms(2), ...
        groupPhaseRms(3), ...
        groupMeanRms, ...
        currentRatio, ...
        currentErrorPercent};

end

