function DB = DCS880_FieldDatabase()
%DCS880_FIELDDATABASE  ABB DCS880 field/excitation converter ratings.
%
%   DB = DCS880_FieldDatabase() returns a struct array, one entry per
%   DCS880 excitation unit, with fields: Type, UV0, Imax, Size.
%   excitation_calculation.m selects the first entry (assumed sorted by
%   ascending capability) whose UV0 and Imax both cover the required
%   values.
%
%   Data values are unchanged from the original.

DB = struct( ...
    'Type', { ...
    'DCS880-S01-0290-06', ...
    'DCS880-S01-0590-06', ...
    'DCS880-S01-0900-06/07', ...
    'DCS880-S01-1500-06/07', ...
    'DCS880-S01-2000-06/07', ...
    'DCS880-S01-2050-06/07', ...
    'DCS880-S01-2500-06/07', ...
    'DCS880-S01-3000-06/07', ...
    'DCS880-S01-3300-06/07', ...
    'DCS880-S01-4000-06/07', ...
    'DCS880-S01-4800-06/07', ...
    'DCS880-S01-1900-08', ...
    'DCS880-S01-2500-08', ...
    'DCS880-S01-3000-08', ...
    'DCS880-S01-3300-08', ...
    'DCS880-S01-4000-08', ...
    'DCS880-S01-4800-08', ...
    'DCS880-S01-2050-10', ...
    'DCS880-S01-2600-10', ...
    'DCS880-S01-3300-10', ...
    'DCS880-S01-4000-10'}, ...
    'UV0', { ...
    600, 600, 690, 690, 690, 690, 690, 690, 690, 690, 690, ...
    800, 800, 800, 800, 800, 800, ...
    990, 990, 990, 990}, ...
    'Imax', { ...
    290, 590, 900, 1500, 2000, 2050, 2500, 3000, 3300, 4000, 4800, ...
    1900, 2500, 3000, 3300, 4000, 4800, ...
    2050, 2600, 3300, 4000}, ...
    'Size', { ...
    'H3', 'H4', 'H6', 'H6', 'H6', 'H7', 'H7', 'H7', 'H8', 'H8', 'H8', ...
    'H7', 'H7', 'H7', 'H8', 'H8', 'H8', ...
    'H8', 'H8', 'H8', 'H8'} ...
    );

%% Validation: all four field-value lists must have matched lengths
n = [numel({DB.Type}), numel({DB.UV0}), numel({DB.Imax}), numel({DB.Size})];
if numel(unique(n)) ~= 1
    error('DCS880_FieldDatabase:LengthMismatch', ...
        'Type/UV0/Imax/Size lists must be the same length (got %s).', ...
        mat2str(n));
end

%% Validation: UV0 should be non-decreasing for the "first match" search
%% used in excitation_calculation.m to behave as intended
if any(diff([DB.UV0]) < 0)
    warning('DCS880_FieldDatabase:NotSorted', ...
        ['UV0 values are not sorted ascending; excitation_calculation''s ' ...
         '"first suitable unit" search may not return the smallest match.']);
end

end
