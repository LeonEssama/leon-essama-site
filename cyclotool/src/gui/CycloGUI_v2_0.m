    function populateLossDetail(Loss)
        fields = fieldnames(Loss);
        data = cell(numel(fields),3);
        for k = 1:numel(fields)
            data{k,1} = fields{k};
            value = Loss.(fields{k});
            if isnumeric(value)
                if isscalar(value)
                    data{k,2} = value;
                elseif numel(value) <= 10
                    data{k,2} = mat2str(value);
                else
                    data{k,2} = sprintf( ...
                        '[%d elements]', ...
                        numel(value));
                end
            elseif islogical(value)
                data{k,2} = value;
            elseif ischar(value)
                data{k,2} = value;
            elseif isstring(value)
                data{k,2} = char(value);
            elseif isstruct(value)
                data{k,2} = sprintf( ...
                    '[STRUCT: %d fields]', ...
                    numel(fieldnames(value)));
            else
                data{k,2} = sprintf( ...
                    '[%s]', ...
                    class(value));
            end
            data{k,3} = '-';
        end
        lossDetailTable.Data = data;
    end
