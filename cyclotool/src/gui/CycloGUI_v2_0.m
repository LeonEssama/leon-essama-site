            49 ];
        DimObj = getBaseDimensioning();
        if isempty(DimObj)
            uialert(fig, [ ...
                'No SCmin dimensioning available. Run Dimensioning for ', ...
                'the SCmin case first -- Grid Harmonics must use the ', ...
                'same dimensioning result the current Netzbelastung ', ...
                'result was generated from.'], ...
                'No Data');
            return
        end
        % Reset storage
        GridHarmonicObjects = {};
        % Summary table
        GridResult = cell(size(Data,1),13);
        DimInput  = DimObj.Input;
        DimResult = DimObj.Result;
        for r = 1:size(Data,1)
            Point       = Data{r,1};
            VoltageCase = Data{r,2};
            IL1     = Data{r,7};
            cosphiL = Data{r,8};
            SCCase  = Data{r,9};
            % This row's actual grid short-circuit power -- ku (grid
            % voltage distortion) must use whichever SC value this row
            % was computed against (SCmin or SCmax), not always SC_min.
            if strcmp(SCCase,'SCmax')
                SCactive = DimInput.SC_max;
            else
                SCactive = DimInput.SC_min;
            end
            % =====================================================
            % ABB aN
            % =====================================================
            arg = cosphiL + ...
                (DimResult.dxN + DimInput.d_r);
            arg = max(min(arg,1),-1);
            aN = acos(arg);
            % =====================================================
            % ABB dx normalization
            % =====================================================
            uLcase = netzMatrixTable.Data{r,12};
            dx = DimResult.dxN / uLcase;
            % Operating-point input values for this row, kept only for
            % the Eingabedaten detail breakdown below (not used in any
            % of the harmonic/sideband formulas themselves).
            Psh_row = netzMatrixTable.Data{r,4};
            Speed_row = netzMatrixTable.Data{r,3};
            UL_row = netzMatrixTable.Data{r,14};
            % =====================================================
            % Overlap angle w -- fixed per explicit user instruction at
            % w = 0.1 pu (10%) for every point/SC case, no longer
            % derived from aN/dx via the ABB overlap-angle formula.
            % "pu" here is taken as a fraction of the pi rad (180 elec.
            % deg) half-cycle reference already used for firing angles
            % in this tool -- this is an engineering interpretation of
            % the per-unit base, not a value cited by any IEC/IEEE
            % standard or the reference VBA (neither defines a per-unit
            % convention for the overlap/commutation angle).
            % =====================================================
            w_pu = 0.1;
            u = w_pu * pi;
            % =====================================================
            % Harmonic spectrum
            % =====================================================
            H = zeros(length(Orders),5);
            for k = 1:length(Orders)
                n = Orders(k);
                aCoeff = ...
                    sin((n-1)*u/2)/(n-1);
                bCoeff = ...
                    sin((n+1)*u/2)/(n+1);
                koeff = 1;
                if DimInput.PulseNumber == 12
                    if ismember(n,[5 7 17 19 29 31 41 43])
                        koeff = 0.1;
                    end
                elseif DimInput.PulseNumber == 24
                    if ismember(n,[5 7 17 19 29 31 41 43])
                        koeff = 0.1;
                    end
                    if ismember(n,[11 13 35 37])
                        koeff = 0.2;
                    end
                end
                KI = ...
                    koeff * ...
                    (1/(n*2*dx)) * ...
                    sqrt( ...
                    aCoeff^2 + ...
                    bCoeff^2 - ...
                    2*aCoeff*bCoeff*cos(2*aN + u)) ...
                    *100;
                IL = KI/100 * IL1;
                S = sqrt(3) * DimResult.Uv0N * IL1;
                ku = KI * n * S / SCactive;
                H(k,:) = [ ...
                    n ...
                    KI ...
                    IL ...
                    ku ...
                    n*DimInput.fL ];
            end
            ku25 = sqrt(sum(H(1:8,4).^2));
            kuTot = sqrt(sum(H(:,4).^2));
            % Store full harmonic spectrum
            GH = struct();
            GH.Point = Point;
            GH.VoltageCase = VoltageCase;
            GH.SCCase = SCCase;
            GH.IL1 = IL1;
            GH.aN  = aN;
            GH.u   = u;
            GH.Characteristic = H;
            % Eingabedaten (input data) for this operating point, for
            % the detail breakdown table only.
            GH.Psh        = Psh_row;
            GH.Speed      = Speed_row;
            GH.UL         = UL_row;
            GH.uLcase     = uLcase;
            GH.SCactive   = SCactive;
            GH.cosphiL    = cosphiL;
            GH.PulseNumber = DimInput.PulseNumber;
            GH.Uv0N       = DimResult.Uv0N;
            GH.dx         = dx;
            GH.aN_deg     = aN * 180/pi;
            GH.w_pu       = w_pu;
            FixedOrders = [2 3 4 6 8 9];
            FixedCoeff = [
                0.3
                0.4
                0.3
                0.3
                0.2
                0.4];
            Fixed = zeros(6,5);
            for m = 1:length(FixedOrders)
                h = FixedOrders(m);
                I = IL1 * FixedCoeff(m)/100;
                Fixed(m,:) = [
                    h ...
                    FixedCoeff(m) ...
                    I ...
                    FixedCoeff(m) ...
                    h*DimInput.fL];
            end
            GH.Fixed = Fixed;
            %% =====================================================
            % ABB Sidebands
            %% =====================================================
            Speed = netzMatrixTable.Data{r,3};
            fM = Speed * DimInput.PolePairs / 60;
            isTrapez = ...
                strcmp(Point,'BaseSpeed') || ...
                strcmp(Point,'MaxSpeed');
            Sidebands = struct([]);
            rowSB = 0;
            %% Fundamental sideband fL ± 6fM
            I5source = H(1,3);   % Order 5 source harmonic
            rowSB = rowSB + 1;
            Sidebands(rowSB).Point = Point;
            Sidebands(rowSB).VoltageCase = VoltageCase;
            Sidebands(rowSB).Order = 1;
            if isTrapez
                Isb = 0.50 * I5source;
            else
                Isb = 0.40 * I5source;
            end
            % Order 1 IS the fundamental, so its Harmonic [A]/[%] is the
            % fundamental grid current itself (GH.IL1, from the Grid
            % Harmonics calculation), not the raw order-5 source current
            % -- per user correction. The Sideband [A]/[%] columns (the
            % actual fL+-6fM sideband amplitude) are unchanged and still
            % derive from I5source.
            Sidebands(rowSB).HarmonicA = IL1;
            Sidebands(rowSB).HarmonicPct = ...
                100 * IL1 / IL1;
            Sidebands(rowSB).CurrentA = Isb;
            Sidebands(rowSB).CurrentPct = ...
                100 * Isb / IL1;
            Sidebands(rowSB).FreqMinus = ...
                DimInput.fL - 6*fM;
            Sidebands(rowSB).FreqPlus = ...
                DimInput.fL + 6*fM;
            for k = 1:size(H,1)
                h  = H(k,1);
                Ih = H(k,3);
                fh = H(k,5);
                if isTrapez
                    HarmonicA = 0.60 * Ih;
                    SidebandA = 0.25 * Ih;
                else
                    HarmonicA = 0.25 * Ih;
                    SidebandA = 0.50 * Ih;
                end
                rowSB = rowSB + 1;
                Sidebands(rowSB).Point = Point;
                Sidebands(rowSB).VoltageCase = VoltageCase;
                Sidebands(rowSB).Order = h;
                Sidebands(rowSB).HarmonicA = HarmonicA;
                Sidebands(rowSB).HarmonicPct = ...
                    100 * HarmonicA / IL1;
                Sidebands(rowSB).CurrentA = SidebandA;
                Sidebands(rowSB).CurrentPct = ...
                    100 * SidebandA / IL1;
                Sidebands(rowSB).FreqMinus = ...
                    fh - 6*fM;
                Sidebands(rowSB).FreqPlus = ...
                    fh + 6*fM;
            end
            for k = 1:size(Fixed,1)
                h  = Fixed(k,1);
                Ih = Fixed(k,3);
                fh = Fixed(k,5);
                % Fixed orders (2,3,4,6,8,9) are ALREADY a defined
                % percentage of IL1 (Ih = IL1*FixedCoeff/100, per user
                % correction) -- Harmonic [A]/[%] must equal that value
                % directly, not have the isTrapez sideband-amplitude
                % factor (0.60/0.25) applied again on top of it. Only
                % the Sideband [A]/[%] columns (the fL+-6fM modulation
                % amplitude) use that factor.
                if isTrapez
                    SidebandA = 0.25 * Ih;
                else
                    SidebandA = 0.50 * Ih;
                end
                rowSB = rowSB + 1;
                Sidebands(rowSB).Point = Point;
                Sidebands(rowSB).VoltageCase = VoltageCase;
                Sidebands(rowSB).Order = h;
                Sidebands(rowSB).HarmonicA = Ih;
                Sidebands(rowSB).HarmonicPct = ...
                    100 * Ih / IL1;
                Sidebands(rowSB).CurrentA = SidebandA;
                Sidebands(rowSB).CurrentPct = ...
                    100 * SidebandA / IL1;
                Sidebands(rowSB).FreqMinus = ...
                    fh - 6*fM;
                Sidebands(rowSB).FreqPlus = ...
                    fh + 6*fM;
            end
            GH.Sidebands = Sidebands;
            [~,idxSort] = sort([Sidebands.Order]);
            GH.Sidebands = Sidebands(idxSort);
            %% =====================================================
            % ABB Report Data
            %% =====================================================
            GH.Report.Point = Point;
            GH.Report.VoltageCase = VoltageCase;
            GH.Report.IL1 = IL1;
            GH.Report.fM = fM;
            GH.Report.fL = DimInput.fL;
            GH.Report.Fixed = GH.Fixed;
            GH.Report.Harmonics = GH.Characteristic;
            GH.Report.Sidebands = GH.Sidebands;
            GH.Report.ku25 = ku25;
            GH.Report.kuTot = kuTot;
            GridHarmonicObjects{r} = GH;
            GridResult(r,:) = {
                Point
                VoltageCase
                ku25
                kuTot
                H(1,2)
                H(1,3)
                H(2,2)
                H(2,3)
                H(3,2)
                H(3,3)
                H(4,2)
                H(4,3)
                SCCase
                };
        end
        % =========================================================
        % Summary Table
        % =========================================================
        gridHarmonicTable.ColumnName = {
            'Point'
            'VoltageCase'
            'ku25 [%]'
            'kuTot [%]'
            'H5 [%]'
            'H5 [A]'
            'H7 [%]'
            'H7 [A]'
            'H11 [%]'
            'H11 [A]'
            'H13 [%]'
            'H13 [A]'
            'SCCase'
            };
        GridResultAll = GridResult;
        % Default the view to whichever case this run's base (row 1) is
        % -- keeps the SC Case dropdown in sync with what was just run.
        gridViewSCDropdown.Value = GridResult{1,13};
        updateGridHarmonicView();
        ABBReportData = buildABBReportData();
    end
