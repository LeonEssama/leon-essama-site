    function h = inputSnapshotHash(InputStruct)
        %INPUTSNAPSHOTHASH  Short content hash of a calculation Input
        % struct. Used to detect when GUI parameters have changed
        % since Dimensioning was last run -- a Dimensioning re-run
        % with different inputs invalidates every downstream cached
        % stage (Operating Point, Harmonics, ... Cooling), and
        % nothing previously flagged that silently. See
        % validateReportCache().
        try
            bytes = getByteStreamFromArray(InputStruct);
            md = java.security.MessageDigest.getInstance('MD5');
            digestBytes = typecast(md.digest(bytes), 'uint8');
            h = sprintf('%02x', digestBytes);
        catch
            % A field that cannot be serialized (e.g. a function
            % handle) must not break the calculation for the sake of
            % a diagnostics feature -- fall back to "always stale".
            h = '';
        end
    end
    function setDropdownItemsSafely(dd, items, fallback)
        %SETDROPDOWNITEMSSAFELY
        % Repopulate a uidropdown's Items list without the classic
        % "Value must be a member of Items" crash: uidropdown
        % validates Value against Items on every property set, so
        % reassigning Items while the dropdown's current (stale,
        % previous-run) Value is not in the new list throws
        % immediately -- this is what broke re-running a tab's
        % calculation after changing an input (e.g. Grid Harmonics:
        % run once, change a parameter, run again -> error). Always
        % go through this helper instead of setting .Items directly.
        if isempty(items)
            dd.Items = {fallback};
            dd.Value = fallback;
            return
        end
        if ~ismember(dd.Value, items)
            % Clear to a value guaranteed valid for the OLD list
            % first, so the Items reassignment below never sees a
            % mismatched Value in between.
            dd.Value = dd.Items{1};
        end
        dd.Items = items;
        dd.Value = items{1};
    end
