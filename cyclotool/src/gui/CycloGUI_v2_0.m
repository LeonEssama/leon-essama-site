    function [maxPVTh_kW, maxPVBesch_kW, maxPVWasser_kW, ...
            srcPVTh, srcPVBesch, srcPVWasser] = ...
            getMaxConverterLossesForCooling()
        %GETMAXCONVERTERLOSSESFORCOOLING  Max PER-DEVICE PV(Th)/PV(Besch)
        %[W] -- PV(Th)/n_Th and PV(Besch)/(n_Th/N_series), per user
        %instruction, since the Water Cooling Design "Thy Loss"/
        %"Resistor Loss" inputs are the loss of ONE thyristor / ONE
        %snubber resistor per cooling-can (KD) branch, not the
        %whole-converter totals PV_Th/PV_Besch calculateLosses.m
        %returns -- and max PV(Wasser) [W] (already a whole-converter
        %total, not divided) -- across every LossObjects entry: every
        %RMS operating point (both SC cases when "Include SCmax case"
        %is on) AND every Peak case (Peak uLmin/Peak 1.0, both SC cases
        %when both have been run). Converted to kW, plus a "Point /
        %VoltageCase" label identifying which entry each max came from
        %(so the Cooling tab can mark the governing case). Returns []/
        %'' for everything if Losses hasn't been run yet. PV(Wasser) is
        %0 for every row unless Losses was last run with Cooling =
        %Water (calculateLosses.m's air-cooled branch always sets it to
        %0), so Losses should be (re-)run with Cooling = Water
        %immediately before Cooling design.
        maxPVTh_kW = [];
        maxPVBesch_kW = [];
        maxPVWasser_kW = [];
        srcPVTh = '';
        srcPVBesch = '';
        srcPVWasser = '';
        if isempty(LossObjects)
            return
        end
        % Iterate rather than concatenate LossObjects{:} into a struct
        % array: the RMS-row entries carry extra fields (uM, uLstar,
        % PavgSolved, IL1ABB, IL1Netz) the Peak-row entries don't --
        % [LossObjects{:}] errors ("Number of fields ... do not match")
        % the moment both kinds are present, since MATLAB struct-array
        % concatenation requires an identical field set on every
        % element.
        bestTh = -Inf;
        bestBesch = -Inf;
        bestWasser = -Inf;
        for k = 1:numel(LossObjects)
            L = LossObjects{k};
            if isempty(L)
                continue
            end
            % n_Th/N_series guarded (default 1, i.e. no division) for a
            % LossObjects entry computed before these fields existed.
            n_Th_L = getResultField(L,'n_Th',1);
            N_series_L = getResultField(L,'N_series',1);
            PV_Th_perDevice = L.PV_Th / n_Th_L;
            PV_Besch_perDevice = L.PV_Besch / (n_Th_L / N_series_L);
            if PV_Th_perDevice > bestTh
                bestTh = PV_Th_perDevice;
                srcPVTh = describeLossSource(L);
            end
            if PV_Besch_perDevice > bestBesch
                bestBesch = PV_Besch_perDevice;
                srcPVBesch = describeLossSource(L);
            end
            if L.PV_Wasser > bestWasser
                bestWasser = L.PV_Wasser;
                srcPVWasser = describeLossSource(L);
            end
        end
        if bestTh > -Inf
            maxPVTh_kW = bestTh / 1000;
        end
        if bestBesch > -Inf
            maxPVBesch_kW = bestBesch / 1000;
        end
        if bestWasser > -Inf
            maxPVWasser_kW = bestWasser / 1000;
        end
    end
    function s = describeLossSource(L)
        %DESCRIBELOSSSOURCE  "Point / VoltageCase" label for a
        %LossObjects entry, for marking which case drove a Cooling
        %design max.
        if isfield(L,'Point') && isfield(L,'VoltageCase')
            s = sprintf('%s / %s', L.Point, L.VoltageCase);
        else
            s = '(unknown)';
        end
    end
    function [maxTein_C, srcTein] = getMaxTeinForCooling()
        %GETMAXTEINFORCOOLING  Max T(W,ein) [deg C] (water inlet
        %temperature required by the thyristor/snubber thermal solve)
        %across every Operating Point Study case (RMS uLmin/1.0/uLmax
        %and Peak uLmin/1.0, both SC cases when both have been run) --
        %feeds the Water Cooling Design "Taus Conv" input, plus a label
        %identifying which case the max came from. Returns []/'' if no
        %valid T(W,ein) is available. A Study case run with Cooling =
        %Air has Tein = NaN (calculate_thyristor_thermal.m only
        %computes it for Water) and is ignored here.
        maxTein_C = [];
        srcTein = '';
        CaseNames = {'RMS uLmin','RMS 1.0','RMS uLmax','Peak uLmin','Peak 1.0'};
        AllStudy = [OperatingPointStudySCmin, OperatingPointStudySCmax];
        bestTein = -Inf;
        bestLabel = '';
        for k = 1:numel(AllStudy)
            R = AllStudy{k};
            if ~isempty(R) && isfield(R,'Tein') && ~isnan(R.Tein) && R.Tein > bestTein
                bestTein = R.Tein;
                caseIdx = mod(k-1,5) + 1;
                if k <= numel(OperatingPointStudySCmin)
                    scLabel = 'SCmin';
                else
                    scLabel = 'SCmax';
                end
                bestLabel = sprintf('%s (%s)', CaseNames{caseIdx}, scLabel);
            end
        end
        if bestTein > -Inf
            maxTein_C = bestTein;
            srcTein = bestLabel;
        end
    end
    function updateCoolingLoadsEstimate()
        %UPDATECOOLINGLOADSESTIMATE  Keep the Water Cooling Design loss/
        %temperature inputs (Thy Loss, Resistor Loss, Converter Loss,
        %Taus Conv) consistent with CoolingLoadsMode. Automatic derives
        %them from the latest Losses/Operating Point results and makes
        %the four fields read-only; Manual leaves them editable, at
        %whatever value the user last set -- same pattern as LsMode/
        %updateLsEstimate() for the Ls field. If Automatic is selected
        %but the required results aren't available yet, alerts and
        %reverts the mode back to Manual instead of leaving read-only
        %fields showing stale/wrong values.
        if strcmpi(CoolingLoadsMode.Value,'Manual')
            ThyristorCoolingLoss.Editable = 'on';
            ResistorCoolingLoss.Editable  = 'on';
            ConverterCoolingLoss.Editable = 'on';
            TausConvMax.Editable          = 'on';
            return
        end
        [maxPVTh_kW, maxPVBesch_kW, maxPVWasser_kW] = ...
            getMaxConverterLossesForCooling();
        maxTein_C = getMaxTeinForCooling();
        if isempty(maxPVTh_kW) || isempty(maxTein_C)
            uialert(fig, [ ...
                'Automatic needs Losses (run with Cooling = Water) and ', ...
                'Operating Point results to derive the Water Cooling ', ...
                'Design inputs -- run those first. Reverted to Manual.'], ...
                'No Data');
            CoolingLoadsMode.Value = 'Manual';
            ThyristorCoolingLoss.Editable = 'on';
            ResistorCoolingLoss.Editable  = 'on';
            ConverterCoolingLoss.Editable = 'on';
            TausConvMax.Editable          = 'on';
            return
        end
        ThyristorCoolingLoss.Value = round(maxPVTh_kW,2);
        ResistorCoolingLoss.Value  = round(maxPVBesch_kW,2);
        ConverterCoolingLoss.Value = round(maxPVWasser_kW,2);
        TausConvMax.Value          = round(maxTein_C,1);
        ThyristorCoolingLoss.Editable = 'off';
        ResistorCoolingLoss.Editable  = 'off';
        ConverterCoolingLoss.Editable = 'off';
        TausConvMax.Editable          = 'off';
    end
    function runCooling(~,~)
        %RUNCOOLING
        % Water-cooling design: calculate_cyclo_water_cooling.m
        % against the workbook "Design of Water-Cooling System for
        % Cycloconverters", populate the Cooling tab (table + the
        % two sweep plots + the sweep table), and feed the Design Data
        % report cache.
        try
            idx = find(strcmp({DB.Type},...
                thyDropdown.Value),1);
            Thy = DB(idx);
            % Auto-derive the Water Cooling Design loss/temperature
            % inputs from the already-computed Losses/Operating Point
            % results when CoolingLoadsMode = Automatic (Thy Loss = max
            % PV(Th), Resistor Loss = max PV(Besch), Converter Loss =
            % max PV(Wasser), all from calculateLosses.m across every
            % operating point, Peak case and SC case; Taus Conv = max
            % T(W,ein) from Operating Point). In Manual mode, the four
            % fields keep whatever value the user typed -- skip this
            % block entirely.
            isAutomatic = strcmpi(CoolingLoadsMode.Value, ...
                'Automatic (from Losses/Operating Point)');
            srcPVTh = ''; srcPVBesch = ''; srcPVWasser = ''; srcTein = '';
            if isAutomatic
                [maxPVTh_kW, maxPVBesch_kW, maxPVWasser_kW, ...
                    srcPVTh, srcPVBesch, srcPVWasser] = ...
                    getMaxConverterLossesForCooling();
                if isempty(maxPVTh_kW)
                    uialert(fig, [ ...
                        'Run Losses first (with Cooling = Water) -- ', ...
                        'the Water Cooling Design inputs (Thy Loss, ', ...
                        'Resistor Loss, Converter Loss) are derived ', ...
                        'from the computed PV(Th)/PV(Besch)/PV(Wasser) ', ...
                        'results in Automatic mode.'], ...
                        'No Data');
                    return
                end
                [maxTein_C, srcTein] = getMaxTeinForCooling();
                if isempty(maxTein_C)
                    uialert(fig, [ ...
                        'Run Operating Point first (with Cooling = ', ...
                        'Water) -- the Water Cooling Design "Taus ', ...
                        'Conv" input is derived from the computed ', ...
                        'T(W,ein) (water inlet temperature) results ', ...
                        'in Automatic mode.'], ...
                        'No Data');
                    return
                end
                ThyristorCoolingLoss.Value = round(maxPVTh_kW,2);
                ResistorCoolingLoss.Value  = round(maxPVBesch_kW,2);
                ConverterCoolingLoss.Value = round(maxPVWasser_kW,2);
                TausConvMax.Value          = round(maxTein_C,1);
            end

            Input = buildInput(Thy);

            CoolingInput = struct();
            CoolingInput.QwKD_lpm = Input.QwKD_lpm;
            CoolingInput.GlycolPercent = Input.GlycolPercent;
            CoolingInput.ConverterType = Input.CoolingConverterType;
            CoolingInput.ThyristorLoss_kW = Input.ThyristorCoolingLoss_kW;
            CoolingInput.ResistorLoss_kW = Input.ResistorCoolingLoss_kW;
            CoolingInput.ConverterLoss_kW = Input.ConverterCoolingLoss_kW;
            CoolingInput.MaxOutletTemperatureKD_C = ...
                Input.MaxOutletTemperatureKD_C;
            CoolingInput.MaxOutletTemperatureConverter_C = ...
                Input.MaxOutletTemperatureConverter_C;

            CoolingResult = ...
                calculate_cyclo_water_cooling(CoolingInput);

            populateCoolingResults(CoolingResult);
            if isAutomatic
                % Mark which operating point/case governs each
                % Automatic-derived loss/temperature input -- e.g. a
                % Peak case, if that turns out to run hotter than every
                % RMS operating point.
                coolingTable.Data = [coolingTable.Data; {
                    'Thy Loss Source',       srcPVTh,     '-'
                    'Resistor Loss Source',  srcPVBesch,  '-'
                    'Converter Loss Source', srcPVWasser, '-'
                    'Taus Conv Source',      srcTein,     '-'
                    }];
            end

            %% Flow sweep plot (Cooling design C26:J26) -- "Water Flow
            % and Pressure Drop": converter pressure drop (left axis)
            % and the converter-level required intake temperature
            % (right axis), both vs. swept water flow, per the
            % reference workbook's chart of the same name.
            Sweep = run_cyclo_cooling_sweep(CoolingInput);
            cla(coolingSweepAx);
            yyaxis(coolingSweepAx,'left');
            plot(coolingSweepAx, ...
                Sweep.QwKD_lpm, Sweep.DpConverter_kPa, ...
                'd-','LineWidth',2,'DisplayName','Pressure drop');
            ylabel(coolingSweepAx,'Pressure drop [kPa]');
            yyaxis(coolingSweepAx,'right');
            plot(coolingSweepAx, ...
                Sweep.QwKD_lpm, Sweep.TinConverter_C, ...
                's-','LineWidth',2,'DisplayName','Intake temperature');
            ylabel(coolingSweepAx,'Intake temperature [°C]');
            xlabel(coolingSweepAx,'Water flow [l/min]');
            title(coolingSweepAx,'Water Flow and Pressure Drop');
            legend(coolingSweepAx,'Location','northwest');
            grid(coolingSweepAx,'on');

            %% Cooling Sweep Table -- Output data (per the reference
            % workbook layout): one column per swept flow rate, the
            % column nearest the actual design flow (Qw [L/min],
            % CoolingInput.QwKD_lpm) highlighted as the design target.
            nFlow = numel(Sweep.QwKD_lpm);
            rowLabels = {
                'Water flow of cycloconverter [l/min]'
                'Pressure drop of cycloconverter [kPa]'
                ''
                'Intake temp required Thyr&R [°C]'
                'delta T cooling in/out [K]'
                ''
                'Intake temp required cycloconv. [°C]'
                'delta T cooling in/out [K]'
                };
            rowData = [ ...
                Sweep.QConverter_lpm'; ...
                Sweep.DpConverter_kPa'; ...
                NaN(1,nFlow); ...
                Sweep.TinKD_C'; ...
                Sweep.DeltaTKD_C'; ...
                NaN(1,nFlow); ...
                Sweep.TinConverter_C'; ...
                Sweep.DeltaTConverter_C'];
            nSweepRows = numel(rowLabels);
            sweepTableData = cell(nSweepRows, 1+nFlow);
            for r = 1:nSweepRows
                sweepTableData{r,1} = rowLabels{r};
                for c = 1:nFlow
                    if isnan(rowData(r,c))
                        sweepTableData{r,c+1} = [];
                    else
                        sweepTableData{r,c+1} = round(rowData(r,c),2);
                    end
                end
            end
            coolingSweepTable.Data = sweepTableData;
            removeStyle(coolingSweepTable);
            [~, targetCol] = min(abs(Sweep.QwKD_lpm - CoolingInput.QwKD_lpm));
            addStyle(coolingSweepTable, ...
                uistyle('BackgroundColor',[0.75 0.85 1]), ...
                'column', targetCol+1);

            %% Glycol sweep plot
            GlycolSweep = run_cyclo_cooling_glycol_sweep(CoolingInput);
            plot(coolingGlycolAx, ...
                GlycolSweep.GlycolPercent, GlycolSweep.DpConverter_kPa, ...
                'o-','LineWidth',2);
            xlabel(coolingGlycolAx,'Glycol [%]');
            ylabel(coolingGlycolAx,'\DeltaP_{Converter} [kPa]');
            title(coolingGlycolAx,'Cooling Glycol Sweep');
            grid(coolingGlycolAx,'on');

            %% Design Data cache
            DesignDataCache.Cooling = CoolingResult;
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);

            if CoolingResult.Status ~= "PASS"
                uialert(fig, ...
                    strjoin(CoolingResult.StatusNotes, newline), ...
                    'Cooling Design Check', ...
                    'Icon','warning');
            end

            tg.SelectedTab = tabCooling;
        catch ME
            uialert(fig,...
                sprintf('Line %d\n%s', ...
                ME.stack(1).line,...
                ME.message),...
                'Cooling Error');
        end
    end
    function runOperatingPoint(~,~)
        try
            if isempty(DimensioningObjects)
                uialert( ...
                    fig,...
                    'Run Dimensioning first.',...
                    'Warning');
                return
            end
            choice = questdlg( ...
                'Select network case', ...
                'Operating Point', ...
                'SCmin', ...
                'SCmax', ...
                'SCmin');
            if isempty(choice)
                return
            end
            %% ===================================================
            % Find latest matching dimensioning
            %% ===================================================
            DesignFound = false;
            for k = numel(DimensioningObjects):-1:1
                if strcmp( ...
                        DimensioningObjects{k}.Case,...
                        choice)
                    D = DimensioningObjects{k};
                    DesignFound = true;
                    break
                end
            end
            if ~DesignFound
                uialert( ...
                    fig,...
                    ['No ' choice ' dimensioning available.'],...
                    'Warning');
                return
            end
            %% ===================================================
            % Base input
            %% ===================================================
            Input = D.Input;
            Input.u_r = D.Result.u_r;
            Input.exT = D.Result.exT;
            %% ===================================================
            % ABB Operating Point Voltages
            %% ===================================================
            uLmin = Input.u_L;
            uLnom = 1.0;
            uLmax = 1 + (1-uLmin);
            %% RMS operating point
            IMnom = Input.IM;
            I1Snom = D.Result.I1S_nom;
            %% Peak operating point
            IMH = D.Result.IM_start;
            I1SH = D.Result.I1S_start;
            %% ===================================================
            % Study container
            %% ===================================================
            Study = {};
            %% ===================================================
            % CASE 1
            % RMS uLmin
            %% ===================================================
            % Undervoltage/field-weakening operating point: at reduced
            % voltage (uLmin < 1) the motor needs more current for the
            % same power, so IM_used here is IM_uL = IM/uLmin (the same
            % formula calculate.m computes into R.IM_uL), not the plain
            % nominal IM used for the other RMS cases.
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLmin;
            Case.IM_used = IMnom / uLmin;
            Case.I1S_used = I1Snom;
            Study{1} = calculate(Case);
            %% ===================================================
            % CASE 2
            % RMS 1.0
            %% ===================================================
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLnom;
            Case.IM_used = IMnom;
            Case.I1S_used = I1Snom;
            Study{2} = calculate(Case);
            %% ===================================================
            % CASE 3
            % RMS uLmax
            %% ===================================================
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLmax;
            Case.IM_used = IMnom;
            Case.I1S_used = I1Snom;
            Study{3} = calculate(Case);
            %% ===================================================
            % CASE 4
            % PEAK uLmin
            %% ===================================================
            Case = Input;
            Case.Mode = 'peak';
            Case.uL_used = uLmin;
            Case.IM_used = IMH;
            Case.I1S_used = I1SH;
            Study{4} = calculate(Case);
            %% ===================================================
            % CASE 5
            % PEAK 1.0
            %% ===================================================
            Case = Input;
            Case.Mode = 'peak';
            Case.uL_used = 1.0;
            Case.IM_used = IMH;
            Case.I1S_used = I1SH;
            Study{5} = calculate(Case);
            %% ===================================================
            % Operating Point table display fields
            %% ===================================================
            % aN for this table is always the reference 90 deg firing
            % angle, not Input.a_Nmin (the minimum commutation-margin
            % angle calculate.m uses internally for dxN) -- fixed for
            % every point. I1S shown is always I1Snom (the dimensioning
            % result's nominal system current), the same reference value
            % for every point including the Peak cases, not each case's
            % own I1S_used (I1SH for Peak, which calculate.m still uses
            % internally for those cases' own thermal/current results --
            % only the displayed I1S row is pinned to I1Snom).
            for k = 1:5
                Study{k}.aN_display = 90;
                Study{k}.I1S_display = I1Snom;
            end
            %% ===================================================
            % Store study
            %% ===================================================
            if strcmp(choice,'SCmin')
                OperatingPointStudySCmin = Study;
            else
                OperatingPointStudySCmax = Study;
            end
            %% ===================================================
            % Temporary cache
            %% ===================================================
            DesignDataCache.OperatingPoint = Study;
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);
            refreshOperatingPointMatrix();
            uialert( ...
                fig,...
                sprintf( ...
                '%s operating point study completed.', ...
                choice),...
                'Operating Point');
        catch ME
            uialert( ...
                fig,...
                ME.message,...
                'Operating Point Error');
        end
    end
    function refreshOperatingPointMatrix()

        % Show whichever case(s) have actually been computed -- SCmin
        % alone right after its own study, updating to include SCmax's
        % columns once that study is also run, instead of waiting for
        % both before showing anything.
        if isempty(OperatingPointStudySCmin) && isempty(OperatingPointStudySCmax)
            return
        end

        Rows = {

        'Id(DB,act)'
        'T(j)'
        'P(L,Th)'
        'P(L,ThS)'
        't(q) [us]'
        'di/dt (akt.)'
        'di/dt (90°)'
        'T(W,ein)'
        'T(KD,mitt)'
        'T(W,aus)'
        'IM used [A]'
        'aN [deg]'
        'I1S [A]'

        };
        nRows = numel(Rows);

        Data = cell(nRows,11);

        for r = 1:nRows
            Data{r,1} = Rows{r};
        end

        EmptyBlock = cell(1,5);
        if isempty(OperatingPointStudySCmin)
            SCminBlock = EmptyBlock;
        else
            SCminBlock = OperatingPointStudySCmin;
        end
        if isempty(OperatingPointStudySCmax)
            SCmaxBlock = EmptyBlock;
        else
            SCmaxBlock = OperatingPointStudySCmax;
        end
        AllResults = [SCminBlock, SCmaxBlock];

        for c = 1:10

            R = AllResults{c};
            if isempty(R)
                continue
            end

            if c <= 3

                Data{1,c+1} = round(R.Id_DBeff,1);

            else

                Data{1,c+1} = round(R.Id_DBpeak,1);

            end
            Data{2,c+1}  = round(R.Tj,1);
            Data{3,c+1}  = round(R.PLTh,1);
            Data{4,c+1}  = round(R.PVS,1);
            Data{5,c+1}  = round(R.tq_actual*1e6,1);
            Data{6,c+1}  = round(R.didtv,3);
            Data{7,c+1}  = round(R.didt90,3);

            if isfield(R,'Tein')
                Data{8,c+1} = round(R.Tein,1);
            else
                Data{8,c+1} = [];
            end

            if isfield(R,'Tav_KD')
                Data{9,c+1} = round(R.Tav_KD,1);
            else
                Data{9,c+1} = [];
            end

            if isfield(R,'Taus_W')
                Data{10,c+1} = round(R.Taus_W,1);
            else
                Data{10,c+1} = [];
            end

            Data{11,c+1} = round(R.IM_used,1);
            % aN_display/I1S_display guarded for projects saved before
            % these two Operating Point table rows existed.
            if isfield(R,'aN_display')
                Data{12,c+1} = R.aN_display;
            else
                Data{12,c+1} = [];
            end
            if isfield(R,'I1S_display')
                Data{13,c+1} = round(R.I1S_display,1);
            else
                Data{13,c+1} = [];
            end

        end

        operatingPointTable.Data = Data;

        removeStyle(operatingPointTable);

        redStyle = uistyle( ...
            'BackgroundColor',[1 0.8 0.8], ...
            'FontWeight','bold');

        for c = 1:10

            R = AllResults{c};
            if isempty(R)
                continue
            end

            Thy = R.Thy;

            %% Tj violation

            if R.Tj > Thy.Tjmax

                addStyle( ...
                    operatingPointTable,...
                    redStyle,...
                    'cell',...
                    [2 c+1]);

            end
            if R.didtv > Thy.di_dt_b

                addStyle( ...
                    operatingPointTable,...
                    redStyle,...
                    'cell',...
                    [6 c+1]);

            end
            if R.tq_actual < Thy.tq

                addStyle( ...
                    operatingPointTable,...
                    redStyle,...
                    'cell',...
                    [5 c+1]);

            end
        end
    end
