    function runLosses(~,~)
        if isempty(NetzOperatingMatrix)
            uialert(fig,...
                'Generate Operating Matrix first.',...
                'No Data');
            return
        end
        if isempty(DimensioningObjects)
            uialert(fig,...
                'Run Dimensioning first.',...
                'No Data');
            return
        end
        D = getBaseDimensioning();
        if isempty(D)
            uialert(fig, [ ...
                'No SCmin dimensioning available. Run Dimensioning for ', ...
                'the SCmin case first -- Losses must use the same ', ...
                'dimensioning result the current operating matrix was ', ...
                'generated from.'], ...
                'No Data');
            return
        end
        Data = NetzOperatingMatrix;
        Results = cell(size(Data,1),10);
        LossObjects = cell(size(Data,1),1);
        for r = 1:size(Data,1)
            Point       = Data{r,1};
            VoltageCase = Data{r,2};
            Speed = Data{r,3};
            Psh   = Data{r,4};
            UM_op      = Data{r,6};
            i_M        = Data{r,7};
            IM_op      = Data{r,8};
            cosphi_M   = Data{r,9};
            g_Faktor   = Data{r,10};
            Uv0N       = Data{r,11};
            uLcase     = Data{r,12};
            u_Lstar    = Data{r,13};
            GridSCC    = Data{r,15};   % holds this row's SC case value (SCmin or SCmax)
            deltaBeta  = Data{r,16};
            SCCase     = Data{r,17};
            % -------------------------------------------------
            % Loss calculation
            % -------------------------------------------------
            % Per-case overrides: D.Input/D.Result are the fixed
            % dimensioning-time (nominal) values: IM and Uv0N vary by
            % operating point (this row of the Netz matrix) and must
            % override them, or PV_Th/PV_Besch/machine losses come out
            % identical for every case.
            InputCase = D.Input;
            InputCase.IM = IM_op;
            DimResultCase = D.Result;
            DimResultCase.Uv0N = Uv0N;
            % PVSch (thyristor switching loss) also depends on the
            % operating point: it scales with the actual thyristor
            % voltage/di-dt at this uLcase, not just the nominal
            % dimensioning-point value used by D.Result.PVS. Re-run the
            % same thermal solve calculate.m uses, at this row's
            % uLcase/IM, holding the converter's fixed design
            % characteristics (I1S, dxN, Uv0N, PulseNumber) at their
            % dimensioning-time values.
            [~, ~, ~, PVSCase] = calculate_thyristor_thermal( ...
                uLcase, D.Result.I1S, D.Result.dxN, D.Result.Uv0N, ...
                D.Input.PulseNumber/6, D.Input.fL, IM_op, IM_op, ...
                D.Input.Mode, D.Input.PulseNumber, D.Input.Cooling, ...
                D.Input.CB, D.Input.Taus_max, D.Input.Qw, D.Input.Tamb, ...
                D.Thy);
            DimResultCase.PVS = PVSCase;
            Loss = calculateLosses( ...
                InputCase,...
                DimResultCase,...
                D.Thy,...
                Speed,...
                uLcase,...
                Psh,...
                D.Result.Psh);
            targetPin = Loss.Pin;
            % -------------------------------------------------
            % Solve uM so that:
            % Pavg ≈ Pin
            % -------------------------------------------------
            uMsolved = solveUM( ...
                targetPin,...
                Speed,...
                UM_op,...
                i_M,...
                IM_op,...
                cosphi_M,...
                g_Faktor,...
                Uv0N,...
                u_Lstar,...
                GridSCC,...
                deltaBeta);
            % Store solved uM back into matrix
            Data{r,5} = uMsolved;
            % -------------------------------------------------
            % Verification
            % -------------------------------------------------
            UL_op = Data{r,14};
            NetzCheck = calculateNetzIL1( ...
                uMsolved,...
                UM_op,...
                i_M,...
                IM_op,...
                cosphi_M,...
                g_Faktor,...
                Uv0N,...
                uLcase,...
                uLcase,...
                UL_op,...
                GridSCC,...
                deltaBeta);
            targetIL1 = calculateABB_IL1( ...
                IM_op,...
                Uv0N,...
                UL_op);
            % Per user instruction: at BaseSpeed and MaxSpeed (Speed >=
            % n_nom, constant-power field-weakening region) operating at
            % uLmin, the ABB IL1 estimate must be divided by uL,min --
            % the same 1/uL scaling already applied to i_M for these
            % uLmin rows in generateNetzMatrix(), so the grid-side
            % current also reflects the reduced line voltage. Creeping/
            % MinSpeed uLmin rows are below n_nom and unaffected (their
            % UM_op there already scales with Speed/n_nom, not u_L).
            if strcmp(VoltageCase,'uLmin') && ...
                    (strcmp(Point,'BaseSpeed') || strcmp(Point,'MaxSpeed'))
                targetIL1 = targetIL1 / uLcase;
            end
            uLstarSolved = solveULstar( ...
                targetIL1,...
                NetzCheck.Savg,...
                UL_op);
            Data{r,13} = uLstarSolved;
            IL1Verify = ...
                NetzCheck.Savg / ...
                (sqrt(3)*uLstarSolved*UL_op);
            % -------------------------------------------------
            % Store results
            % -------------------------------------------------
            Results(r,:) = {
                Point
                VoltageCase
                round(Loss.PV_Th,0)
                round(Loss.PV_Besch,0)
                round(Loss.Machine,0)
                round(Loss.Transformer,0)
                round(Loss.Converter,0)
                round(Loss.Total,0)
                round(Loss.Pin,0)
                SCCase
                };
            Loss.uM = uMsolved;
            Loss.uLstar = uLstarSolved;
            Loss.PavgSolved = NetzCheck.Pavg;
            Loss.IL1ABB = targetIL1;
            Loss.IL1Netz = NetzCheck.IL1;
            Loss.SCCase = SCCase;
            Loss.Point = Point;
            Loss.VoltageCase = VoltageCase;
            LossObjects{r,1} = Loss;
        end
        nRMSRows = size(Data,1);
        % -------------------------------------------------
        % Peak-case losses: the RMS-based operating matrix above has no
        % "Peak" concept -- Peak uLmin/Peak 1.0 only exist as Operating
        % Point Study cases 4/5 (calculate.m run with Mode='peak',
        % IM_used=IM_start). Add one Losses row per Peak case, per SC
        % case actually present in the current matrix, per user
        % instruction:
        %   - IM_used = that SC case's own IM_start (Dcase.Result.
        %     IM_start), not the nominal Input.IM the RMS rows use.
        %   - PVSch = that SC case's own Operating Point Study{4}/{5}.
        %     PVS, reused directly (the RMS rows above re-solve PVS
        %     because they sweep uLcase/IM across an operating matrix
        %     the Peak Study does not cover).
        %   - Speed/Psh = that SC case's nominal n_nom/Psh, matching
        %     the Peak Study cases themselves, which are not
        %     speed-swept (same convention as the RMS BaseSpeed rows).
        % Unlike the RMS rows (numerically identical across SC cases,
        % since they always use the SCmin-baseline D), Peak rows
        % genuinely differ per SC case: IM_start/PVS both come from
        % that case's own independently-dimensioned Operating Point
        % Study. So the displayed Point is suffixed "(SCmin)"/"(SCmax)"
        % to disambiguate (both in the table and for selectLossCase()
        % matching below), instead of silently collapsing to one case
        % like the RMS rows' display does.
        PeakSCCaseNames = unique(Data(:,17),'stable');
        PeakVoltageNames = {'uLmin','1.0'};
        PeakResults = cell(2*numel(PeakSCCaseNames),10);
        PeakLossObjects = cell(2*numel(PeakSCCaseNames),1);
        prow = 0;
        for s = 1:numel(PeakSCCaseNames)
            SCName = PeakSCCaseNames{s};
            if strcmp(SCName,'SCmax')
                Dcase = [];
                for kk = numel(DimensioningObjects):-1:1
                    if strcmp(DimensioningObjects{kk}.Case,'SCmax')
                        Dcase = DimensioningObjects{kk};
                        break
                    end
                end
                StudyCase = OperatingPointStudySCmax;
            else
                Dcase = D;
                StudyCase = OperatingPointStudySCmin;
            end
            if isempty(Dcase)
                uialert(fig, [ ...
                    'No ' SCName ' dimensioning available -- needed ', ...
                    'for the Peak-case Losses rows (IM_start).'], ...
                    'No Data');
                return
            end
            if numel(StudyCase) < 5 || isempty(StudyCase{4}) || isempty(StudyCase{5})
                uialert(fig, [ ...
                    'Run Operating Point for ' SCName ' first -- the ', ...
                    'Peak uLmin/Peak 1.0 Losses rows need its Study ', ...
                    'cases 4/5 (IM_start, PVSch).'], ...
                    'No Data');
                return
            end
            PeakPointLabel = sprintf('Peak (%s)', SCName);
            for k = 4:5
                prow = prow + 1;
                VoltageCase = PeakVoltageNames{k-3};
                if k == 4
                    uLcase_peak = Dcase.Input.u_L;
                else
                    uLcase_peak = 1.0;
                end
                InputCase = Dcase.Input;
                InputCase.IM = Dcase.Result.IM_start;
                DimResultCase = Dcase.Result;
                DimResultCase.PVS = StudyCase{k}.PVS;
                Speed_peak = Dcase.Input.n_nom;
                Psh_peak = Dcase.Result.Psh;
                Loss = calculateLosses( ...
                    InputCase, DimResultCase, Dcase.Thy, ...
                    Speed_peak, uLcase_peak, Psh_peak, Psh_peak);
                Loss.SCCase = SCName;
                Loss.Point = PeakPointLabel;
                Loss.VoltageCase = VoltageCase;
                PeakResults(prow,:) = {
                    PeakPointLabel
                    VoltageCase
                    round(Loss.PV_Th,0)
                    round(Loss.PV_Besch,0)
                    round(Loss.Machine,0)
                    round(Loss.Transformer,0)
                    round(Loss.Converter,0)
                    round(Loss.Total,0)
                    round(Loss.Pin,0)
                    SCName
                    };
                PeakLossObjects{prow,1} = Loss;
            end
        end
        Results = [Results; PeakResults];
        LossObjects = [LossObjects; PeakLossObjects];
        % -------------------------------------------------
        % Update operating matrix
        % -------------------------------------------------
        netzMatrixTable.Data = Data;
        NetzOperatingMatrix = Data;
        % -------------------------------------------------
        % Update losses table
        % -------------------------------------------------
        % Loss.* for the RMS rows never depends on GridSCC (grid
        % short-circuit power) -- calculateLosses() takes Speed/Psh/IM/
        % Uv0N/uLcase, none of which differ between the SCmin and SCmax
        % RMS rows for the same operating point -- so the SCmin and
        % SCmax RMS blocks of Results are numeric duplicates of each
        % other. Show only the base RMS block (the first 12 rows,
        % always SCmin -- generateNetzMatrix() always emits 'SCmin'
        % first) plus every Peak row (which DOES genuinely differ per
        % SC case, see above), while LossObjects/Results stay complete
        % internally (both RMS SC-case blocks) for Netzbelastung, which
        % needs a per-row, per-case solved u_M/u_Lstar.
        RMSResults = Results(1:nRMSRows,:);
        baseCase = RMSResults{1,10};
        displayRMS = strcmp(RMSResults(:,10), baseCase);
        LossResults = [RMSResults(displayRMS,1:9); PeakResults(:,1:9)];
        lossTable.Data = LossResults;
        lossTable.CellSelectionCallback = @selectLossCase;
    end
    function selectLossCase(~, event)
        if isempty(event.Indices)
            return
        end
        row = event.Indices(1);
        if row > size(LossResults,1)
            return
        end
        % Match by identity (Point/VoltageCase), not positional index:
        % the displayed table (SCmin RMS block + all Peak rows) is not
        % in the same order/count as LossObjects (which also holds the
        % SCmax RMS block when present).
        targetPoint = LossResults{row,1};
        targetVoltage = LossResults{row,2};
        for k = 1:numel(LossObjects)
            L = LossObjects{k};
            if ~isempty(L) && isfield(L,'Point') && ...
                    strcmp(L.Point,targetPoint) && strcmp(L.VoltageCase,targetVoltage)
                populateLossDetail(L);
                return
            end
        end
    end
    function populateLossDetail(Loss)
        % Curated PV breakdown, per the VBA Verlustrechnung (MEGADRIVE-
        % CYCLO, P. Burmeister 2000) and matching the reference table's
        % row order/grouping. PV(3 GL) and PV(Si) are omitted: this tool
        % has no n(s)>1 series-thyristor or fuse-datasheet inputs for
        % them (per user direction).
        % PV_Luft/PV_Wasser/PV_TotRes guarded: a project saved before
        % this fix won't have them on its stored LossObjects entries.
        breakdown = {
            'PV(Th)',      Loss.PV_Th,     'W'
            'PV(Besch)',   Loss.PV_Besch,  'W'
            'PV(Zus)',     Loss.PV_Zus,    'W'
            '',            [],             ''
            'PV(Tot+Res)', getResultField(Loss,'PV_TotRes',NaN), 'W'
            '',            [],             ''
            'PV(Luft)',    getResultField(Loss,'PV_Luft',NaN),   'W'
            'PV(Wasser)',  getResultField(Loss,'PV_Wasser',NaN), 'W'
            };
        nBreak = size(breakdown,1);
        totResRow = find(strcmp(breakdown(:,1),'PV(Tot+Res)'),1);

        fields = fieldnames(Loss);
        data = cell(numel(fields)+nBreak,3);
        data(1:nBreak,:) = breakdown;
        for k = 1:numel(fields)
            r = k + nBreak;
            data{r,1} = fields{k};
            value = Loss.(fields{k});
            if isnumeric(value)
                if isscalar(value)
                    data{r,2} = value;
                elseif numel(value) <= 10
                    data{r,2} = mat2str(value);
                else
                    data{r,2} = sprintf( ...
                        '[%d elements]', ...
                        numel(value));
                end
            elseif islogical(value)
                data{r,2} = value;
            elseif ischar(value)
                data{r,2} = value;
            elseif isstring(value)
                data{r,2} = char(value);
            elseif isstruct(value)
                data{r,2} = sprintf( ...
                    '[STRUCT: %d fields]', ...
                    numel(fieldnames(value)));
            else
                data{r,2} = sprintf( ...
                    '[%s]', ...
                    class(value));
            end
            data{r,3} = '-';
        end
        lossDetailTable.Data = data;
        removeStyle(lossDetailTable);
        addStyle(lossDetailTable, uistyle('FontWeight','bold'), 'row', totResRow);
    end
