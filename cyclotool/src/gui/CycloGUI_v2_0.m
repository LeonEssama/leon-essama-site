            CaseNames = {
                'RMS uLmin'
                'RMS 1.0'
                'RMS uLmax'
                'Peak uLmin'
                'Peak 1.0'
                };

            for k = 1:min(5,length(OPStudy))
                CaseResult = OPStudy{k};
                HInput = D.Input;
                if strcmp(choice,'SCmin')
                    HInput.SCact = HInput.SC_min;
                else
                    HInput.SCact = HInput.SC_max;
                end
                H = harmonic_calculation( ...
                    HInput,...
                    CaseResult);
                H.Name = CaseNames{k};
                Study{k} = H;
            end
            %% Store latest analytical harmonics for Design Data generation

            DesignDataCache.Input = ...
                D.Input;
            DesignDataCache.Harmonics = Study;
            if isempty(DesignDataCache.Harmonics)
                error( ...
                    'Cyclo:DesignDataHarmonicCacheFailure', ...
                    ['The Design Data cache did not receive the latest ', ...
                    'analytical harmonic calculation.']);
            end
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);
            %% Store study
            HO = struct();
            HO.Case = choice;
            HO.Time = char( ...
                datetime('now', ...
                'Format','yyyy-MM-dd HH:mm:ss'));
            HO.Input = D.Input;
            HO.Study = Study;
            HarmonicObjects{end+1} = HO;
            %% Keep maximum 5 studies
            if numel(HarmonicObjects) > MaxCases
                HarmonicObjects(1) = [];
            end
            %% Refresh summary table
            refreshHarmonicTable();
        catch ME
            uialert(fig,...
                ME.message,...
                'Harmonic Error');
        end
    end
