    function runDimensioning(~,~)
        try
            choice = questdlg( ...
                'Select network case', ...
                'Dimensioning', ...
                'SCmin', ...
                'SCmax', ...
                'SCmin');
            if isempty(choice)
                return
            end
            %% Build Input
            idx = find(strcmp({DB.Type},...
                thyDropdown.Value),1);
            Thy = DB(idx);
            Input = buildInput(Thy);
            %% Store selected case
            Input.CaseName = choice;
            %% Dimensioning
            % calculate.m's commutation-reactance formula (dxN) reads a
            % single Input.SC_min as "the active grid short-circuit
            % power" -- when the user picks the SCmax case, feed it
            % SC_max via a separate copy, not by overwriting Input.SC_min
            % itself. Input (stored below into DimObj.Input) must keep
            % SC_min and SC_max as their true, distinct GUI values, or
            % downstream consumers (generateNetzMatrix's SCmin/SCmax
            % dual-case matrix) see the same value for both cases.
            DimensioningInput = Input;
            if strcmp(choice,'SCmax')
                DimensioningInput.SC_min = Input.SC_max;
            end
            R = cyclo_dimensioning(DimensioningInput);
            R = ...
                cyclo_attach_case_metadata( ...
                R, ...
                Input, ...
                "Dimensioning", ...
                "1.2 Development");
            %% Store latest result for Design Data generation

            DesignDataCache.Input = ...
                Input;
            DesignDataCache.Dimensioning = ...
                R;
            DesignDataCache.Meta.DimensioningInputHash = ...
                inputSnapshotHash(Input);
            if isempty(DesignDataCache.Input) || ...
                    isempty(DesignDataCache.Dimensioning)
                error( ...
                    'Cyclo:DesignDataDimensioningCacheFailure', ...
                    ['The Design Data cache did not receive the latest ', ...
                    'dimensioning calculation.']);
            end
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);

            %% Status evaluation

            if R.k_N >= Input.kN_min && ...
                    abs(R.Uv0N - Input.Uv0N_target) <= 0.01*Input.Uv0N_target && ...
                    R.IkN <= 1.01*Thy.IKS0
                Status = 'PASS';
            else
                Status = 'FAIL';
            end
            DimObj = struct();
            DimObj.Case = choice;
            DimObj.Time = ...
                char( ...
                datetime( ...
                'now', ...
                'Format', ...
                'yyyy-MM-dd HH:mm:ss'));
            DimObj.Input = Input;
            DimObj.Result = R;
            DimObj.Thy = Thy;
            DimensioningObjects{end+1} = DimObj;
            if numel(DimensioningObjects) > MaxCases
                DimensioningObjects(1) = [];
            end
            WaveRow = {
                choice,...
                char( ...
                datetime( ...
                'now', ...
                'Format', ...
                'HH:mm:ss')),...
                R.IM_uL,...
                R.IM_ovld,...
                R.IM_start,...
                R.Id_DBeff_nom,...
                R.Id_DBpeak_nom,...
                R.Id_DBeff_ovld,...
                R.Id_DBpeak_ovld,...
                R.I1S_nom,...
                R.I1S_ovld,...
                R.ISi
                };
            WaveformHistory(end+1,:) = WaveRow;
            if size(WaveformHistory,1) > MaxCases
                WaveformHistory(1,:) = [];
            end
            waveHistoryTable.Data = WaveformHistory;
            %% Add history row
            NewRow = {
                choice,...
                char( ...
                datetime( ...
                'now', ...
                'Format', ...
                'HH:mm:ss')),...
                Thy.Type,...
                R.Uv0N,...
                R.IkN,...
                R.k_N,...
                R.Tj,...
                R.tq_actual*1e6,...
                Status
                };
            DimensioningHistory(end+1,:) = NewRow;
            %% Keep 5 rows maximum
            if size(DimensioningHistory,1) > MaxCases
                DimensioningHistory(1,:) = [];
            end
            dimensioningTable.Data = ...
                DimensioningHistory;
            dimensioningTable.CellSelectionCallback = ...
                @selectDimensioningCase;
            populateDimensioningResults( ...
                DimensioningObjects{end});
            populateDimensioningDetail( ...
                DimensioningObjects{end}.Result);
            try
                if ~isempty(BusbarUI)
                    BusbarUI.refresh();
                end
            catch busbarErr
                warning('CycloGUI:BusbarRefresh', ...
                    'Busbar check did not update: %s', busbarErr.message);
            end
            tg.SelectedTab = tabResults;
        catch ME
            uialert(fig,...
                sprintf('Line %d\n%s', ...
                ME.stack(1).line,...
                ME.message),...
                'Dimensioning Error');
        end
    end
