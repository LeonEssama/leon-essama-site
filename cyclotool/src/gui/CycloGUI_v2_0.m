    function loadProject(~,~)
        [file,path] = ...
            uigetfile('*.mat','Load Project');
        if isequal(file,0)
            return
        end
        S = load(fullfile(path,file));
        Project = S.Project;
        %% Restore inputs
        restoreProject(Project);
        %% Restore results
        if isfield(Project,'Results')
            DimensioningHistory = ...
                Project.Results.DimensioningHistory;
            DimensioningObjects = ...
                Project.Results.DimensioningObjects;
            WaveformHistory = ...
                Project.Results.WaveformHistory;
            OperatingPointStudySCmin = ...
                Project.Results.OperatingPointSCmin;
            OperatingPointStudySCmax = ...
                Project.Results.OperatingPointSCmax;
            HarmonicObjects = ...
                Project.Results.HarmonicObjects;
            CharacteristicObjects = ...
                Project.Results.CharacteristicObjects;
            FiringAngleObjects = ...
                Project.Results.FiringAngleObjects;
            ExcitationObjects = ...
                Project.Results.ExcitationObjects;
        end
        %% Restore DesignDataCache
        if isfield(Project,'DesignDataCache')
            DesignDataCache = ...
                Project.DesignDataCache;
        end
        CurrentProjectFile = ...
            fullfile(path,file);
        %% Refresh visible tables
        dimensioningTable.Data = ...
            DimensioningHistory;
        waveHistoryTable.Data = ...
            WaveformHistory;
        refreshOperatingPointMatrix();
        refreshHarmonicTable();
        %% Show latest dimensioning
        if ~isempty(DimensioningObjects)
            populateDimensioningResults( ...
                DimensioningObjects{end});
            populateDimensioningDetail( ...
                DimensioningObjects{end}.Result);
        end
        %% Show latest characteristic
        if ~isempty(CharacteristicObjects)
            showCharacteristic( ...
                CharacteristicObjects{end}.Result);
        end
        %% Show latest firing study
        if ~isempty(FiringAngleObjects)
            showFiringAngle( ...
                FiringAngleObjects{end}.Result);
        end
        %% Show latest excitation study
        if ~isempty(ExcitationObjects)
            showExcitation( ...
                ExcitationObjects{end}.Result);
        end
        uialert(fig,...
            'Project loaded successfully.',...
            'Load');
    end
    function newProject(~,~)
        answer = uiconfirm( ...
            fig,...
            'Discard current project and start new?',...
            'New Project');

        if ~strcmp(answer,'OK')
            return
        end
        CurrentProjectFile = '';
        resetInputsToDefault();
        %% Clear all studies
        DimensioningHistory = {};
