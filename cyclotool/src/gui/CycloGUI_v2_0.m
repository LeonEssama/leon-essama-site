    function generateNetzMatrix(~,~)
        netzMatrixTable.ColumnName = {
            'Point'
            'VoltageCase'
            'Speed'
            'Psh'
            'u_M'
            'UM'
            'i_M'
            'IM'
            'cosphi_M'
            'g_Faktor'
            'Uv0N'
            'u_L'
            'u_Lstar'
            'UL'
            'Grid SCC Power'
            'deltaBeta'
            'SCCase'
            };
        if isempty(DimensioningObjects)

            uialert(fig,...
                'Run Dimensioning first.',...
                'No Data');

            return

        end

        D = getBaseDimensioning();
        if isempty(D)
            uialert(fig, [ ...
                'No SCmin dimensioning available. Run Dimensioning for ', ...
                'the SCmin case first -- it is the baseline the ', ...
                'operating matrix, Losses, Grid Harmonics and Spectrum ', ...
                'are all generated against.'], ...
                'No Data');
            return
        end
        Input = D.Input;
        R     = D.Result;
        SpeedValues = [ ...
            Input.CreepingSpeed ; ...
            Input.n_min ; ...
            Input.n_nom ; ...
            Input.n_max ];
        SpeedNames = {
            'Creeping'
            'MinSpeed'
            'BaseSpeed'
            'MaxSpeed'
            };
        VoltageNames = {
            'uLmin'
            'uL=1'
            'uLmax'
            };
        % Base case is always SCmin (D is guaranteed SCmin-tagged by
        % getBaseDimensioning() above) -- the SC assumption D.Result was
        % actually computed against. "Include SCmax case" additionally
        % adds SCmax rows using the SAME D.Result (dxN, Uv0N, Psh etc.
        % are not independently re-dimensioned per case -- only the
        % Grid SCC Power value differs between the two blocks of rows).
        if netzIncludeSCmax.Value
            SCCaseNames  = {'SCmin', 'SCmax'};
            SCCaseValues = [Input.SC_min, Input.SC_max];
        else
            SCCaseNames  = {'SCmin'};
            SCCaseValues = Input.SC_min;
        end
        data = cell(12*numel(SCCaseNames),17);
        row = 0;
        for s = 1:numel(SCCaseNames)
            SCName  = SCCaseNames{s};
            SCValue = SCCaseValues(s);
            for i = 1:4
                Speed = SpeedValues(i);
                Pnom = R.Psh;
                if Speed <= Input.n_nom
                    Psh = Pnom * Speed / Input.n_nom;
                else
                    Psh = Pnom;
                end
                UMnom = Input.UM;
                for j = 1:3
                    row = row + 1;
                    switch j
                        case 1
                            uL_op = Input.u_L;
                        case 2
                            uL_op = 1.0;
                        case 3
                            uL_op = 2 - Input.u_L;
                    end
                    if Speed < Input.n_nom
                        UM_op = UMnom * Speed / Input.n_nom;
                    else
                        if j == 1
                            UM_op = UMnom * Input.u_L;
                        else
                            UM_op = UMnom;
                        end
                    end
                    if j == 1

                        iM = 1 / uL_op;

                    else

                        iM = 1.0;

                    end
                    if Speed < Input.n_nom
                        gFaktorOP = 1.0;
                    else
                        gFaktorOP = Input.g_Faktor;
                    end
                    data(row,:) = {
                        SpeedNames{i}
                        VoltageNames{j}
                        Speed
                        Psh
                        1.00          % initial guess for u_M
                        UM_op
                        iM            % ABB logic
                        Input.IM
                        Input.cosphi_M
                        gFaktorOP
                        R.Uv0N
                        uL_op
                        uL_op         % initial guess u_Lstar
                        Input.UL
                        SCValue
                        1
                        SCName
                        };
                end
            end
        end
        netzMatrixTable.Data = data;
        NetzOperatingMatrix = data;
        netzStatus.Text = 'Matrix Generated';
    end
    function runNetzbelastung(~,~)
        Data = netzMatrixTable.Data;
        if isempty(Data)
            return
        end
        if isempty(LossObjects) || numel(LossObjects) < size(Data,1) || ...
                any(cellfun(@isempty, LossObjects(1:size(Data,1))))
            uialert(fig, [ ...
                'Run Losses first. Losses solves u_M and u_Lstar (columns ', ...
                '''u_M''/''u_Lstar'' in the operating matrix) so the network ', ...
                'loading matches the actual Pin (Psh + losses), not just ', ...
                'the crude initial guess Generate Operating Matrix sets. ', ...
                'Netzbelastung needs those solved values for every row of ', ...
                'the current operating matrix (both SC cases if both are ', ...
                'present) before its result is meaningful.'], ...
                'Run Losses First');
            return
        end
        Result = cell(size(Data,1),7);
        BelastungResult = cell(size(Data,1),9);
        for r = 1:size(Data,1)
            Speed = Data{r,3};
            u_M        = Data{r,5};
            UM_op      = Data{r,6};
            i_M        = Data{r,7};
            IM_op      = Data{r,8};
            cosphi_M   = Data{r,9};
            g_Faktor   = Data{r,10};
            Uv0N       = Data{r,11};
            u_L        = Data{r,12};
            u_Lstar    = Data{r,13};
            UL_op      = Data{r,14};
            GridSCC    = Data{r,15};   % holds this row's SC case value (SCmin or SCmax)
            deltaBeta  = Data{r,16};
            SCCase     = Data{r,17};
            Udmax = (1/g_Faktor) * sqrt(2/3) * UM_op;
            if Speed < 1
                % Special ABB Creeping mode
                Flanke = 0.5;
                Trapezbetrieb = false;
                Udvirt = ...
                    u_M * sqrt(2/3) * UM_op;
            else
                Flanke = (1/0.6) * ...
                    (1.3 - sqrt(2/3)*UM_op*u_M/Udmax);
                if Flanke >= 0.5
                    Trapezbetrieb = false;
                    Flanke = 0.5;
                    Udvirt = ...
                        u_M * sqrt(2/3) * UM_op;
                else
                    Trapezbetrieb = true;
                    Udvirt = ...
                        Udmax / sin(Flanke*pi);
                end
            end
            P_sum = 0;
            Q_sum = 0;
            Beta = 0.5;
            Integral = 0;
            while Beta <= 180
                Beta_Pi = Beta*pi/180;
                if ~Trapezbetrieb
                    Ud_x = Udvirt * sin(Beta_Pi);
                elseif Beta > Flanke*180 && ...
                        Beta < (1-Flanke)*180
                    Ud_x = Udmax;
                else
                    Ud_x = Udvirt * sin(Beta_Pi);
                end
                arg = Ud_x / ...
                    (u_L * (sqrt(18)/pi) * Uv0N);
                arg = max(min(arg,1),-1);
                Phi_x_Strich = acos(arg);
                Id_x = sqrt(2) * IM_op * i_M * ...
                    sin(Beta_Pi - acos(cosphi_M));
                Pdi0_x = ...
                    (sqrt(18)/pi) * ...
                    Uv0N * Id_x;
                tanphi_x = ...
                    (1/cos(Phi_x_Strich))* ...
                    ( sin(Phi_x_Strich) ...
                    - abs(Pdi0_x)/GridSCC );
                P_x = abs(Id_x * Ud_x);
                Q_x = abs(P_x * tanphi_x);
                P_sum = P_sum + P_x;
                Q_sum = Q_sum + Q_x;
                Integral = Integral + 1;
                Beta = Beta + deltaBeta;
            end
            Pavg = 3*P_sum/Integral;
            Qavg = 3*Q_sum/Integral;
            Savg = sqrt(Pavg^2 + Qavg^2);
            cosphiL = Pavg / Savg;
            IL1 = Savg / ...
                (sqrt(3)*u_Lstar*UL_op);
            BelastungResult(r,:) = {
                Data{r,1}
                Data{r,2}
                Flanke
                Pavg
                Qavg
                Savg
                IL1
                cosphiL
                SCCase
                };
            Result(r,:) = {
                Data{r,1}
                Data{r,2}
                Udmax
                Flanke
                Trapezbetrieb
                Udvirt
                SCCase
                };
        end
        netzResultTable.ColumnName = {
            'Point'
            'VoltageCase'
            'Udmax'
            'Flanke'
            'Trapezbetrieb'
            'Udvirt'
            'SCCase'
            };
        netzResultTable.Data = Result;
        NetzBetriebsartResults = Result;
        NetzBelastungResults = BelastungResult;
        % One summary row per (speed point x SC case actually present in
        % this matrix) -- four rows when only the Dimensioning-chosen
        % case was computed, eight when "Include SCmax case" added the
        % other one, so SCmin and SCmax results are both visible and
        % not merged when both are present.
        SpeedPoints = {
            'Creeping'
            'MinSpeed'
            'BaseSpeed'
            'MaxSpeed'
            };
        SCCaseNames = unique(BelastungResult(:,9),'stable');
        Summary = cell(numel(SpeedPoints)*numel(SCCaseNames),7);
        k = 0;
        for sc = 1:numel(SCCaseNames)
            for sp = 1:numel(SpeedPoints)
                k = k + 1;
                Name = SpeedPoints{sp};
                SCName = SCCaseNames{sc};
                rows = strcmp(BelastungResult(:,1),Name) & ...
                    strcmp(BelastungResult(:,9),SCName);
                Pvals  = cell2mat(BelastungResult(rows,4));
                Qvals  = cell2mat(BelastungResult(rows,5));
                ILvals = cell2mat(BelastungResult(rows,7));
                FlankeVals = [];
                for m = find(rows).'
                    FlankeVals(end+1) = Result{m,4}; %#ok<AGROW>
                end
                Summary(k,:) = {
                    Name
                    SCName
                    max(FlankeVals)
                    max(Pvals)/1e6
                    max(Qvals)/1e6
                    max(ILvals)
                    mean(cell2mat(BelastungResult(rows,8)))
                    };
            end
        end
        NetzSummaryResults = Summary;
        netzSummaryTable.ColumnName = {
            'Point'
            'SCCase'
            'Max ΔT/T'
            'Max Pavg [MW]'
            'Max Qavg [MVAr]'
            'Max IL1 [A]'
            'Avg cosphiL'
            };
        netzKPITable.ColumnName = {...
            'Worst ΔT/T',...
            'Worst IL1 [A]',...
            'Worst Qavg [MVAr]',...
            'Worst cosphiL'};
        netzStatus.Text = 'Calculation Complete';
        % Default the view to whichever case this run's base (row 1) is
        % -- keeps the SC Case dropdown in sync with what was just run,
        % same as the Converter Harmonics tab.
        netzViewSCDropdown.Value = BelastungResult{1,9};
        updateNetzResultView();
    end
    function netzMatrixCellEdited(~,~)
        % Any manual edit to an editable operating-matrix cell (u_M,
        % i_M, cosphi_M, g_Faktor, u_Lstar, deltaBeta) invalidates the
        % Losses solve and the Netzbelastung result computed from it, so
        % re-run the full Losses -> Netzbelastung chain right away
        % instead of leaving stale results on screen until the buttons
        % are pressed again. Both functions already process every row
        % of the current operating matrix in one pass -- SCmin only, or
        % SCmin and SCmax together when "Include SCmax case" is on --
        % so a single edit recalculates and republishes both SC cases.
        NetzOperatingMatrix = netzMatrixTable.Data;
        netzStatus.Text = 'Recalculating...';
        drawnow;
        runLosses([],[]);
        runNetzbelastung([],[]);
    end
    function updateNetzResultView(~,~)
        caseName = netzViewSCDropdown.Value;
        switch netzViewDropdown.Value
            case 'Betriebsart'
                netzResultTable.ColumnName = {
                    'Point'
                    'VoltageCase'
                    'Udmax'
                    'Flanke'
                    'Trapezbetrieb'
                    'Udvirt'
                    'SCCase'
                    };
                FullResults = NetzBetriebsartResults;
                caseCol = 7;
            case 'Netzbelastung'
                netzResultTable.ColumnName = {
                    'Point'
                    'VoltageCase'
                    'DeltaT/T'
                    'Pavg'
                    'Qavg'
                    'Savg'
                    'IL1'
                    'cosphiL'
                    'SCCase'
                    };
                FullResults = NetzBelastungResults;
                caseCol = 9;
        end
        if isempty(FullResults)
            % Nothing computed at all yet -- Run Netzbelastung first,
            % same as before this SC Case selector existed.
            netzResultTable.Data = {};
            netzSummaryTable.Data = {};
            netzKPITable.Data = {};
            return
        end
        rows = strcmp(FullResults(:,caseCol), caseName);
        if ~any(rows)
            netzResultTable.Data = {};
            netzSummaryTable.Data = {};
            netzKPITable.Data = {};
            alertCaseNotCalculated(caseName);
            return
        end
        netzResultTable.Data = FullResults(rows,:);
        if ~isempty(NetzSummaryResults)
            netzSummaryTable.Data = ...
                NetzSummaryResults(strcmp(NetzSummaryResults(:,2),caseName),:);
        end
        if ~isempty(NetzBelastungResults)
            kpiRows = strcmp(NetzBelastungResults(:,9), caseName);
            if any(kpiRows)
                B = NetzBelastungResults(kpiRows,:);
                netzKPITable.Data = { ...
                    max(cell2mat(B(:,3))), ...
                    max(cell2mat(B(:,7))), ...
                    max(cell2mat(B(:,5)))/1e6, ...
                    min(cell2mat(B(:,8)))};
            end
        end
        if ~lossesReadyForCase(caseName)
            uialert(fig, sprintf([ ...
                'The operating matrix has changed since this %s ', ...
                'Netzbelastung result was computed -- Losses has not ', ...
                'been (re-)run for the current matrix''s %s rows, so ', ...
                'u_M/u_Lstar there are no longer the Losses-solved ', ...
                'values this result used. Run Losses, then Calculate ', ...
                'Netzbelastung again for %s.'], ...
                caseName, caseName, caseName), ...
                'Losses Out Of Date');
        end
    end
    function tf = lossesReadyForCase(caseName)
        %LOSSESREADYFORCASE  True only if every row of the current
        %operating matrix tagged with caseName ('SCmin'/'SCmax') has a
        %corresponding LossObjects entry -- i.e. Losses was run against
        %this exact matrix for this case, so the matrix's u_M/u_Lstar
        %for that case are the Losses-solved values Netzbelastung's
        %displayed result actually used, not stale initial guesses.
        tf = false;
        if isempty(NetzOperatingMatrix) || isempty(LossObjects)
            return
        end
        found = false;
        for r = 1:size(NetzOperatingMatrix,1)
            if strcmp(NetzOperatingMatrix{r,17}, caseName)
                found = true;
                if r > numel(LossObjects) || isempty(LossObjects{r})
                    return
                end
            end
        end
        tf = found;
    end
