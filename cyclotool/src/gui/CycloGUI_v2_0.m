    function runFiringAngle(~,~)

        %% Select dimensioning case
        choice = questdlg( ...
            'Select network case', ...
            'Firing Angle Study', ...
            'SCmin', ...
            'SCmax', ...
            'SCmin');
        if isempty(choice)
            return
        end
        try

            %% Check dimensioning exists
            if isempty(DimensioningObjects)
                uialert(fig,...
                    'Run Dimensioning first.',...
                    'Warning');
                return
            end
            %% Find selected dimensioning case
            Found = false;
            for k = numel(DimensioningObjects):-1:1
                if strcmp(DimensioningObjects{k}.Case,choice)
                    D = DimensioningObjects{k};
                    Found = true;
                    break
                end
            end
            if ~Found
                uialert(fig,...
                    ['No ' choice ' dimensioning available.'],...
                    'Warning');
                return
            end
            %% Update Gamma0 from GUI
            InputFA = D.Input;
            InputFA.gamma0 = gamma0.Value;
            if strcmp(choice,'SCmin')
                InputFA.SCact = InputFA.SC_min;
            else
                InputFA.SCact = InputFA.SC_max;
            end
            %% Run calculation
            F = firing_angle_calculation( ...
                InputFA,...
                D.Result);
            %% Store latest firing-angle result for Design Data generation

            DesignDataCache.Input = ...
                InputFA;

            DesignDataCache.FiringAngle = ...
                F;

            if isempty(DesignDataCache.FiringAngle)

                error( ...
                    'Cyclo:DesignDataFiringAngleCacheFailure', ...
                    ['The Design Data cache did not receive the latest ', ...
                    'firing-angle calculation.']);

            end

            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);

            %% Store study
            FO = struct();
            FO.Case = choice;
            FO.SCact = InputFA.SCact;
            FO.Input = InputFA;
            FO.Result = F;
            FiringAngleObjects{end+1} = FO;
            %% Keep maximum number of studies
            if numel(FiringAngleObjects) > MaxCases
                FiringAngleObjects(1) = [];
            end
            %% Refresh display
            refreshFiringAngle();
        catch ME

            uialert(fig,...
                ME.message,...
                'Firing Angle Error');
        end
    end
    function refreshFiringAngle()
        %% Latest study
        F = FiringAngleObjects{end}.Result;
        %% VBA data table
        points = [0 0.5 1 1.5 2 2.5 3];
        data = cell(length(points),5);
        for k = 1:length(points)
            ipu = points(k);
            data(k,:) = {
                ipu,...
                interp1(F.Ipu,F.WorstCase,ipu),...
                interp1(F.Ipu,F.Allowed,ipu),...
                interp1(F.Ipu,F.Setting,ipu),...
                interp1(F.Ipu,F.Tolerance,ipu)
                };
        end
        firingDataTable.Data = data;
        %% Study history
        n = numel(FiringAngleObjects);
