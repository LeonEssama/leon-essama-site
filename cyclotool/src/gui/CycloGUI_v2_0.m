    function plotABBFrequencyMap(GH)
        %PLOTABBFREQUENCYMAP  Static harmonic/inter-harmonic family map
        %(unchanged) plus, when GH (a GridHarmonicObjects entry, with
        %its computed Sidebands) is supplied, an overlay of that exact
        %operating point's actual computed sideband frequencies --
        %marker size scaled by Sideband [A] amplitude -- so the plot
        %reads dynamically from the Sidebands table instead of only
        %showing the generic full-speed-range family lines.
        if nargin < 1
            GH = [];
        end
        cla(spectrumAx)
        legend(spectrumAx,'off');   % drop any stale bubble-size legend from a previous call
        DBase = getBaseDimensioning();
        if isempty(DBase)
            % Defensive fallback only -- by the time this plot function
            % runs (from updateSidebandDetail/updateGridHarmonicView),
            % Grid Harmonics has already required an SCmin dimensioning
            % to exist, so this should not be reachable in practice.
            DBase = DimensioningObjects{end};
        end
        Input = DBase.Input;
        fL_op = Input.fL;
        Speed = linspace( ...
            0,...
            Input.n_max,...
            800);
        fM = ...
            Speed * Input.PolePairs / 60;
        Orders = [ ...
            1 ...
            5 ...
            7 ...
            11 ...
            13 ...
            17 ...
            19 ...
            23 ...
            25 ...
            29 ...
            31 ...
            35 ...
            37 ...
            41 ...
            43 ...
            47 ...
            49 ];
        ymax = max(Orders) * fL_op * 1.05;
        hold(spectrumAx,'on')
        %% ========================================
        % Plot harmonic families
        %% ========================================
        for k = 1:length(Orders)
            h = Orders(k);
            fh = h * fL_op;
            %% Centre harmonic
            plot( ...
                spectrumAx,...
                Speed,...
                fh * ones(size(Speed)),...
                'Color',[0 0 0],...
                'LineWidth',1.2);
            %% Lower sideband
            plot( ...
                spectrumAx,...
                Speed,...
                fh - 6*fM,...
                '--',...
                'Color',[0.2 0.2 0.2],...
                'LineWidth',0.8);
            %% Upper sideband
            plot( ...
                spectrumAx,...
                Speed,...
                fh + 6*fM,...
                '--',...
                'Color',[0.2 0.2 0.2],...
                'LineWidth',0.8);
        end
        %% ========================================
        % Vertical operating-point markers
        %% ========================================
        xline( ...
            spectrumAx,...
            Input.CreepingSpeed,...
            ':',...
            'Creeping', ...
            'LabelOrientation','horizontal');
        xline( ...
            spectrumAx,...
            Input.n_min,...
            ':',...
            'Min', ...
            'LabelOrientation','horizontal');
        xline( ...
            spectrumAx,...
            Input.n_nom,...
            ':',...
            'Base', ...
            'LabelOrientation','horizontal');
        xline( ...
            spectrumAx,...
            Input.n_max,...
            ':',...
            'Max', ...
            'LabelOrientation','horizontal');
        %% ========================================
        % Labels only on important harmonics
        %% ========================================
        labelOrders = [ ...
            1 5 7 11 13 ...
            17 19 23 25 ...
            35 37 49];
        for h = labelOrders
            fh = h * fL_op;
            text( ...
                spectrumAx,...
                Input.n_max * 1.02,...
                fh,...
                sprintf('%df_L',h),...
                'FontSize',9,...
                'Color',[0 0 0]);
        end
        %% ========================================
        % Overlay: this operating point's actual computed sidebands
        % (GH.Sidebands), marker size scaled by Sideband [A] amplitude
        % -- makes the plot read dynamically from the Sidebands table
        % instead of only showing the generic full-speed-range family
        % lines above. All rows (real harmonic orders AND Fixed orders
        % 2/3/4/6/8/9) share the same x = this point's Speed.
        %% ========================================
        if ~isempty(GH) && isfield(GH,'Sidebands') && ~isempty(GH.Sidebands)
            speedPoint = getResultField(GH,'Speed',NaN);
            if ~isnan(speedPoint)
                freqs = [[GH.Sidebands.FreqMinus], [GH.Sidebands.FreqPlus]];
                amps  = [[GH.Sidebands.CurrentA],  [GH.Sidebands.CurrentA]];
                xPts  = speedPoint * ones(size(freqs));
                % Marker area scale: MATLAB scatter's size argument is
                % marker AREA in points^2, so a size ratio of r maps to
                % a visual diameter ratio of sqrt(r) -- pick a minimum
                % floor (20, so a near-zero-amplitude sideband is still
                % visible) plus a range spanning up to 200 at this
                % point's own largest Sideband [A].
                SIZE_FLOOR = 20;
                SIZE_RANGE = 180;
                maxAmp = max(amps);
                if maxAmp > 0
                    sizes = SIZE_FLOOR + SIZE_RANGE * (amps / maxAmp);
                else
                    sizes = SIZE_FLOOR * ones(size(amps));
                end
                scatter( ...
                    spectrumAx, xPts, freqs, sizes, ...
                    [0.85 0.1 0.1], 'filled', ...
                    'MarkerFaceAlpha', 0.75, ...
                    'MarkerEdgeColor', [0.4 0 0], ...
                    'HandleVisibility', 'off');
                text( ...
                    spectrumAx, speedPoint, ymax * 0.99, ...
                    sprintf('%s / %s', ...
                        getResultField(GH,'Point','?'), ...
                        getResultField(GH,'VoltageCase','?')), ...
                    'FontSize', 8, 'Color', [0.6 0 0], ...
                    'HorizontalAlignment', 'center', ...
                    'VerticalAlignment', 'top');
                % Bubble-size legend: three reference markers, drawn at
                % NaN (invisible, off-plot) purely to calibrate the
                % legend entries, sized with the exact same formula as
                % the real markers above and labelled with the actual
                % Sideband [A] value each size represents -- otherwise
                % "marker size" has no readable scale.
                if maxAmp > 0
                    legendFracs = [1.0 0.5 0.15];
                    legendAmps  = legendFracs * maxAmp;
                    legendSizes = SIZE_FLOOR + SIZE_RANGE * legendFracs;
                else
                    legendAmps  = 0;
                    legendSizes = SIZE_FLOOR;
                end
                legendHandles = gobjects(1,numel(legendAmps));
                for m = 1:numel(legendAmps)
                    legendHandles(m) = scatter( ...
                        spectrumAx, NaN, NaN, legendSizes(m), ...
                        [0.85 0.1 0.1], 'filled', ...
                        'MarkerFaceAlpha', 0.75, ...
                        'MarkerEdgeColor', [0.4 0 0], ...
                        'DisplayName', sprintf('%.2f A', legendAmps(m)));
                end
                sbLegend = legend( ...
                    spectrumAx, legendHandles, ...
                    'Location', 'southeast', ...
                    'AutoUpdate', 'off', ...
                    'FontSize', 8);
                sbLegend.Title.String = 'Sideband [A]';
            end
        end
        %% ========================================
        % Formatting
        %% ========================================
        hold(spectrumAx,'off')
        grid(spectrumAx,'on')
        spectrumAx.GridColor = ...
            [0.85 0.85 0.85];
        box(spectrumAx,'on')
        xlabel( ...
            spectrumAx,...
            'Motor Speed [rpm]');
        ylabel( ...
            spectrumAx,...
            'Frequency [Hz]');
        title( ...
            spectrumAx,...
            'Cycloconverter Harmonic and Inter-Harmonic Frequency Map');
        xlim( ...
            spectrumAx,...
            [0 Input.n_max * 1.15]);
        ylim( ...
            spectrumAx,...
            [0 ymax]);
        %% ========================================
        % ABB style info box
        %% ========================================
        text( ...
            spectrumAx,...
            Input.n_max * 0.04,...
            ymax * 0.94,...
            sprintf([ ...
            'f_L = %.0f Hz supply system frequency\n' ...
            'f_M = variable motor frequency\n' ...
            'Orders shown: 1, 5, 7, 11, 13 ... 49'],...
            fL_op),...
            'BackgroundColor',[1 1 1],...
            'EdgeColor',[0.6 0.6 0.6],...
            'Margin',5,...
            'FontSize',10);
    end
