    function generateNetzMatrix(~,~)
        netzMatrixTable.ColumnName = {
            'Point'
            'VoltageCase'
            'Speed'
            'Psh'
            'u_M'
            'UM'
            'i_M'
            'IM'
            'cosphi_M'
            'g_Faktor'
            'Uv0N'
            'u_L'
            'u_Lstar'
            'UL'
            'SCmin'
            'deltaBeta'
            };
        if isempty(DimensioningObjects)

            uialert(fig,...
                'Run Dimensioning first.',...
                'No Data');

            return

        end

        D = DimensioningObjects{end};
        Input = D.Input;
        R     = D.Result;
        SpeedValues = [ ...
            Input.CreepingSpeed ; ...
            Input.n_min ; ...
            Input.n_nom ; ...
            Input.n_max ];
        SpeedNames = {
            'Creeping'
            'MinSpeed'
            'BaseSpeed'
            'MaxSpeed'
            };
        VoltageNames = {
            'uLmin'
            'uL=1'
            'uLmax'
            };
        data = cell(12,16);
        row = 0;
        for i = 1:4
            Speed = SpeedValues(i);
            Pnom = R.Psh;
            if Speed <= Input.n_nom
                Psh = Pnom * Speed / Input.n_nom;
            else
                Psh = Pnom;
            end
            UMnom = Input.UM;
            for j = 1:3
                row = row + 1;
                switch j
                    case 1
                        uL = Input.u_L;
                    case 2
                        uL = 1.0;
                    case 3
                        uL = 2 - Input.u_L;
                end
                if Speed < Input.n_nom
                    UM = UMnom * Speed / Input.n_nom;
                else
                    if j == 1
                        UM = UMnom * Input.u_L;
                    else
                        UM = UMnom;
                    end
                end
                if j == 1

                    iM = 1 / uL;

                else

                    iM = 1.0;

                end
                if Speed < Input.n_nom
                    gFaktorOP = 1.0;
                else
                    gFaktorOP = Input.g_Faktor;
                end
                data(row,:) = {
                    SpeedNames{i}
                    VoltageNames{j}
                    Speed
                    Psh
                    1.00          % initial guess for u_M
                    UM
                    iM            % ABB logic
                    Input.IM
                    Input.cosphi_M
                    gFaktorOP
                    R.Uv0N
                    uL
                    uL            % initial guess u_Lstar
                    Input.UL
                    Input.SC_min
                    1
                    };
            end
        end
        netzMatrixTable.Data = data;
        NetzOperatingMatrix = data;
        netzStatus.Text = 'Matrix Generated';
    end
    function runNetzbelastung(~,~)
        Data = netzMatrixTable.Data;
        if isempty(Data)
            return
        end
        Result = cell(size(Data,1),6);
        BelastungResult = cell(size(Data,1),8);
        for r = 1:size(Data,1)
            Speed = Data{r,3};
            Psh = Data{r,4};
            Pin = Psh;
            if ~isempty(LossObjects) && ...
                    length(LossObjects) >= r && ...
                    ~isempty(LossObjects{r})
                Pin = LossObjects{r}.Pin;
            end
            u_M        = Data{r,5};
            UM         = Data{r,6};
            i_M        = Data{r,7};
            IM         = Data{r,8};
            cosphi_M   = Data{r,9};
            g_Faktor   = Data{r,10};
            Uv0N       = Data{r,11};
            u_L        = Data{r,12};
            u_Lstar    = Data{r,13};
            UL         = Data{r,14};
            SCmin      = Data{r,15};
            deltaBeta  = Data{r,16};
            Udmax = (1/g_Faktor) * sqrt(2/3) * UM;
            if Speed < 1
                % Special ABB Creeping mode
                Flanke = 0.5;
                Trapezbetrieb = false;
                Udvirt = ...
                    u_M * sqrt(2/3) * UM;
            else
                Flanke = (1/0.6) * ...
                    (1.3 - sqrt(2/3)*UM*u_M/Udmax);
                if Flanke >= 0.5
                    Trapezbetrieb = false;
                    Flanke = 0.5;
                    Udvirt = ...
                        u_M * sqrt(2/3) * UM;
                else
                    Trapezbetrieb = true;
                    Udvirt = ...
                        Udmax / sin(Flanke*pi);
                end
            end
            P_sum = 0;
            Q_sum = 0;
            Beta = 0.5;
            Integral = 0;
            while Beta <= 180
                Beta_Pi = Beta*pi/180;
                if ~Trapezbetrieb
                    Ud_x = Udvirt * sin(Beta_Pi);
                elseif Beta > Flanke*180 && ...
                        Beta < (1-Flanke)*180
                    Ud_x = Udmax;
                else
                    Ud_x = Udvirt * sin(Beta_Pi);
                end
                arg = Ud_x / ...
                    (u_L * (sqrt(18)/pi) * Uv0N);
                arg = max(min(arg,1),-1);
                Phi_x_Strich = acos(arg);
                Id_x = sqrt(2) * IM * i_M * ...
                    sin(Beta_Pi - acos(cosphi_M));
                Pdi0_x = ...
                    (sqrt(18)/pi) * ...
                    Uv0N * Id_x;
                tanphi_x = ...
                    (1/cos(Phi_x_Strich))* ...
                    ( sin(Phi_x_Strich) ...
                    - abs(Pdi0_x)/SCmin );
                P_x = abs(Id_x * Ud_x);
                Q_x = abs(P_x * tanphi_x);
                P_sum = P_sum + P_x;
                Q_sum = Q_sum + Q_x;
                Integral = Integral + 1;
                Beta = Beta + deltaBeta;
            end
            Pavg = 3*P_sum/Integral;
            Qavg = 3*Q_sum/Integral;
            Savg = sqrt(Pavg^2 + Qavg^2);
            cosphiL = Pavg / Savg;
            IL1 = Savg / ...
                (sqrt(3)*u_Lstar*UL);
            BelastungResult(r,:) = {
                Data{r,1}
                Data{r,2}
                Flanke
                Pavg
                Qavg
                Savg
                IL1
                cosphiL
                };
            Result(r,:) = {
                Data{r,1}
                Data{r,2}
                Udmax
                Flanke
                Trapezbetrieb
                Udvirt
                };
        end
        netzResultTable.ColumnName = {
            'Point'
            'VoltageCase'
            'Udmax'
            'Flanke'
            'Trapezbetrieb'
            'Udvirt'
            };
        netzResultTable.Data = Result;
        NetzBetriebsartResults = Result;
        NetzBelastungResults = BelastungResult;
        Summary = cell(4,6);
        SpeedPoints = {
            'Creeping'
            'MinSpeed'
            'BaseSpeed'
            'MaxSpeed'
            };
        for k = 1:4
            Name = SpeedPoints{k};
            rows = strcmp(BelastungResult(:,1),Name);
            Pvals  = cell2mat(BelastungResult(rows,4));
            Qvals  = cell2mat(BelastungResult(rows,5));
            ILvals = cell2mat(BelastungResult(rows,7));
            FlankeVals = [];
            for m = find(rows).'
                FlankeVals(end+1) = Result{m,4};
            end
            Summary(k,:) = {
                Name
                max(FlankeVals)
                max(Pvals)/1e6
                max(Qvals)/1e6
                max(ILvals)
                mean(cell2mat(BelastungResult(rows,8)))
                };
        end
        NetzSummaryResults = Summary;
        WorstDeltaT = max(cell2mat(BelastungResult(:,3)));
        WorstIL1 = max(cell2mat(BelastungResult(:,7)));
        WorstQavg = max(cell2mat(BelastungResult(:,5)));
        WorstCosPhi = min(cell2mat(BelastungResult(:,8)));
        netzKPITable.ColumnName = {...
            'Worst ΔT/T',...
            'Worst IL1 [A]',...
            'Worst Qavg [MVAr]',...
            'Worst cosphiL'};
        netzKPITable.Data = { ...
            WorstDeltaT,...
            WorstIL1,...
            WorstQavg/1e6,...
            WorstCosPhi};
        netzSummaryTable.ColumnName = {
            'Point'
            'Max ΔT/T'
            'Max Pavg [MW]'
            'Max Qavg [MVAr]'
            'Max IL1 [A]'
            'Avg cosphiL'
            };
        netzSummaryTable.Data = NetzSummaryResults;
        netzStatus.Text = 'Calculation Complete';
        updateNetzResultView();
    end
