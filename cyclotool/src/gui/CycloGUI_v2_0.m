    function runLosses(~,~)
        if isempty(NetzOperatingMatrix)
            uialert(fig,...
                'Generate Operating Matrix first.',...
                'No Data');
            return
        end
        if isempty(DimensioningObjects)
            uialert(fig,...
                'Run Dimensioning first.',...
                'No Data');
            return
        end
        D = DimensioningObjects{end};
        Data = NetzOperatingMatrix;
        Results = cell(size(Data,1),9);
        LossObjects = cell(size(Data,1),1);
        for r = 1:size(Data,1)
            Point       = Data{r,1};
            VoltageCase = Data{r,2};
            Speed = Data{r,3};
            Psh   = Data{r,4};
            UM         = Data{r,6};
            i_M        = Data{r,7};
            IM         = Data{r,8};
            cosphi_M   = Data{r,9};
            g_Faktor   = Data{r,10};
            Uv0N       = Data{r,11};
            uLcase     = Data{r,12};
            u_Lstar    = Data{r,13};
            SCmin      = Data{r,15};
            deltaBeta  = Data{r,16};
            % -------------------------------------------------
            % Loss calculation
            % -------------------------------------------------
            % Per-case overrides: D.Input/D.Result are the fixed
            % dimensioning-time (nominal) values: IM and Uv0N vary by
            % operating point (this row of the Netz matrix) and must
            % override them, or PV_Th/PV_Besch/machine losses come out
            % identical for every case.
            InputCase = D.Input;
            InputCase.IM = IM;
            DimResultCase = D.Result;
            DimResultCase.Uv0N = Uv0N;
            % PVSch (thyristor switching loss) also depends on the
            % operating point: it scales with the actual thyristor
            % voltage/di-dt at this uLcase, not just the nominal
            % dimensioning-point value used by D.Result.PVS. Re-run the
            % same thermal solve calculate.m uses, at this row's
            % uLcase/IM, holding the converter's fixed design
            % characteristics (I1S, dxN, Uv0N, PulseNumber) at their
            % dimensioning-time values.
            [~, ~, ~, PVSCase] = calculate_thyristor_thermal( ...
                uLcase, D.Result.I1S, D.Result.dxN, D.Result.Uv0N, ...
                D.Input.PulseNumber/6, D.Input.fL, IM, IM, ...
                D.Input.Mode, D.Input.PulseNumber, D.Input.Cooling, ...
                D.Input.CB, D.Input.Taus_max, D.Input.Qw, D.Input.Tamb, ...
                D.Thy);
            DimResultCase.PVS = PVSCase;
            Loss = calculateLosses( ...
                InputCase,...
                DimResultCase,...
                D.Thy,...
                Speed,...
                uLcase,...
                Psh);
            targetPin = Loss.Pin;
            % -------------------------------------------------
            % Solve uM so that:
            % Pavg ≈ Pin
            % -------------------------------------------------
            uMsolved = solveUM( ...
                targetPin,...
                Speed,...
                UM,...
                i_M,...
                IM,...
                cosphi_M,...
                g_Faktor,...
                Uv0N,...
                u_Lstar,...
                SCmin,...
                deltaBeta);
            % Store solved uM back into matrix
            Data{r,5} = uMsolved;
            % -------------------------------------------------
            % Verification
            % -------------------------------------------------
            UL = Data{r,14};
            NetzCheck = calculateNetzIL1( ...
                uMsolved,...
                UM,...
                i_M,...
                IM,...
                cosphi_M,...
                g_Faktor,...
                Uv0N,...
                uLcase,...
                uLcase,...
                UL,...
                SCmin,...
                deltaBeta);
            targetIL1 = calculateABB_IL1( ...
                IM,...
                Uv0N,...
                UL);
            uLstarSolved = solveULstar( ...
                targetIL1,...
                NetzCheck.Savg,...
                UL);
            Data{r,13} = uLstarSolved;
            IL1Verify = ...
                NetzCheck.Savg / ...
                (sqrt(3)*uLstarSolved*UL);
            % -------------------------------------------------
            % Store results
            % -------------------------------------------------
            Results(r,:) = {
                Point
                VoltageCase
                round(Loss.PV_Th,0)
                round(Loss.PV_Besch,0)
                round(Loss.Machine,0)
                round(Loss.Transformer,0)
                round(Loss.Converter,0)
                round(Loss.Total,0)
                round(Loss.Pin,0)
                };
            Loss.uM = uMsolved;
            Loss.uLstar = uLstarSolved;
            Loss.PavgSolved = NetzCheck.Pavg;
            Loss.IL1ABB = targetIL1;
            Loss.IL1Netz = NetzCheck.IL1;
            LossObjects{r,1} = Loss;
        end
        % -------------------------------------------------
        % Update operating matrix
        % -------------------------------------------------
        netzMatrixTable.Data = Data;
        NetzOperatingMatrix = Data;
        % -------------------------------------------------
        % Update losses table
        % -------------------------------------------------
        lossTable.Data = Results;
        LossResults = Results;
        lossTable.CellSelectionCallback = @selectLossCase;
    end
