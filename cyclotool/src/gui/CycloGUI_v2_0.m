    function updateLsEstimate()
        %UPDATELSESTIMATE  Keep the Ls [mH] field consistent with the
        %selected Ls Source. In either Estimate mode, Ls is computed
        %from nameplate/equivalent-circuit data and made read-only; in
        %Manual mode the field is left editable and untouched.
        if strcmpi(LsMode.Value,'Estimate (Salient-Pole)')
            Ls.Editable = 'off';
            try
                LsEstimated_H = estimate_salient_pole_Ls( ...
                    UM.Value, IM.Value, nNom.Value, PolePairs.Value, ...
                    Xdpp.Value/100);
                Ls.Value = LsEstimated_H*1000;
            catch ME
                uialert(fig, ME.message, 'Ls Estimate Error');
            end
        elseif strcmpi(LsMode.Value,'Estimate (Equivalent Circuit)')
            Ls.Editable = 'off';
            try
                LsEstimated_H = estimate_ls_from_equivalent_circuit( ...
                    UM.Value, IM.Value, nNom.Value, PolePairs.Value, ...
                    xaDelta.Value, xad.Value, xfc.Value);
                Ls.Value = LsEstimated_H*1000;
            catch ME
                uialert(fig, ME.message, 'Ls Estimate Error');
            end
        else
            Ls.Editable = 'on';
        end
    end
    function updateRsEstimate()
        %UPDATERSESTIMATE  Keep the Rs [Ohm] field consistent with the
        %selected Rs Source: Rs = ra_pu * Zbase, Zbase = (UM/sqrt(3))/IM,
        %same base as the equivalent-circuit Ls estimate.
        if strcmpi(RsMode.Value,'From ra [pu]')
            Rs.Editable = 'off';
            Zbase = (UM.Value/sqrt(3))/IM.Value;
            Rs.Value = ra.Value*Zbase;
        else
            Rs.Editable = 'on';
        end
    end
    function updateMotorEstimates()
        %UPDATEMOTORESTIMATES  UM/IM feed both the Ls and Rs estimates
        %(shared Zbase); refresh whichever is in an Estimate mode.
        updateLsEstimate();
        updateRsEstimate();
    end
