    function runOVProtection(~,~)
        try
            % Require dimensioning first
            if isempty(DimensioningObjects)
                error('Run Dimensioning first.');
            end
            % Use latest dimensioning result
            D = DimensioningObjects{end};
            % Auto Stator Uv0: Uv0N / n, n = PulseNumber/6 secondary
            % transformer windings (1/2/3 for 6/12/18-pulse). D.Result.Uv0N
            % (calculate.m R.Uv0N) is the FULL series-stacked transformer
            % secondary voltage across all n windings, so dividing by n
            % gives the per-winding ("one secondary stator transformer")
            % voltage the crowbar BOD element actually sees -- see
            % StatorUv0Mode.Tooltip. Must run before buildInput() below,
            % which reads Uv0_stator.Value.
            if strcmpi(StatorUv0Mode.Value,'Auto (n x Uv0N)')
                n_windings = D.Input.PulseNumber / 6;
                Uv0_stator.Value = D.Result.Uv0N / n_windings;
            end
            % Auto Rotor Uv0: DCS880 rated input (AC secondary) voltage,
            % i.e. the Excitation tab's currently selected UV0_Selected --
            % see RotorUv0Mode.Tooltip. Refreshed here too in case the
            % Excitation UV0_Selected dropdown changed since the last
            % updateRotorUv0Mode() call.
            if strcmpi(RotorUv0Mode.Value,'Auto (DCS880 UV0)')
                Uv0_Rotor.Value = str2double(UV0_Selected.Value);
            end
            % Build standard input, carrying the Dimensioning-selected
            % thyristor (Input.Thy) through -- overvoltage_protection_
            % calculation.m needs its UDRM for the stator VDRM and the
            % Dauergrenzstrom check.
            Input = buildInput(D.Thy);
            % Maximum motor current for crowbar sizing (workbook I(M,max));
            % also shown read-only on the input tab (IMmax_Display), which
            % otherwise has no visible source for this value before Calculate.
            Input.IMmax_OV = D.Result.IM_start;
            IMmax_Display.Value = D.Result.IM_start;
            % Run OV calculation
            O = overvoltage_protection_calculation(Input);
            %% Store latest protection result for Design Data generation

            DesignDataCache.Protection = ...
                O;
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);
            showOVProtection(O);
        catch ME
            uialert(fig,...
                ME.message,...
                'OV Protection Error');
        end
    end
