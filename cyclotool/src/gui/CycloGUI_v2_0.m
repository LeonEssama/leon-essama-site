    function runGridHarmonics(~,~)
        if isempty(NetzBelastungResults)
            uialert(fig,...
                'Run Netzbelastung first.',...
                'No Data');
            return
        end
        Data = NetzBelastungResults;
        Orders = [ ...
            5
            7
            11
            13
            17
            19
            23
            25
            29
            31
            35
            37
            41
            43
            47
            49 ];
        % Reset storage
        GridHarmonicObjects = {};
        % Summary table
        GridResult = cell(size(Data,1),12);
        DimObj    = DimensioningObjects{end};
        DimInput  = DimObj.Input;
        DimResult = DimObj.Result;
        for r = 1:size(Data,1)
            Point       = Data{r,1};
            VoltageCase = Data{r,2};
            IL1     = Data{r,7};
            cosphiL = Data{r,8};
            % =====================================================
            % ABB aN
            % =====================================================
            arg = cosphiL + ...
                (DimResult.dxN + DimInput.d_r);
            arg = max(min(arg,1),-1);
            aN = acos(arg);
            % =====================================================
            % ABB dx normalization
            % =====================================================
            uLcase = netzMatrixTable.Data{r,12};
            dx = DimResult.dxN / uLcase;
            % =====================================================
            % ABB overlap angle
            % =====================================================
            acosArg = cos(aN) - 2*dx;
            acosArg = max(min(acosArg,1),-1);
            u = acos(acosArg) - aN;
            % =====================================================
            % Harmonic spectrum
            % =====================================================
            H = zeros(length(Orders),5);
            for k = 1:length(Orders)
                n = Orders(k);
                aCoeff = ...
                    sin((n-1)*u/2)/(n-1);
                bCoeff = ...
                    sin((n+1)*u/2)/(n+1);
                koeff = 1;
                if DimInput.PulseNumber == 12
                    if ismember(n,[5 7 17 19 29 31 41 43])
                        koeff = 0.1;
                    end
                elseif DimInput.PulseNumber == 24
                    if ismember(n,[5 7 17 19 29 31 41 43])
                        koeff = 0.1;
                    end
                    if ismember(n,[11 13 35 37])
                        koeff = 0.2;
                    end
                end
                KI = ...
                    koeff * ...
                    (1/(n*2*dx)) * ...
                    sqrt( ...
                    aCoeff^2 + ...
                    bCoeff^2 - ...
                    2*aCoeff*bCoeff*cos(2*aN + u)) ...
                    *100;
                IL = KI/100 * IL1;
                S = sqrt(3) * DimResult.Uv0N * IL1;
                ku = KI * n * S / DimInput.SC_min;
                H(k,:) = [ ...
                    n ...
                    KI ...
                    IL ...
                    ku ...
                    n*DimInput.fL ];
            end
            ku25 = sqrt(sum(H(1:8,4).^2));
            kuTot = sqrt(sum(H(:,4).^2));
            % Store full harmonic spectrum
            GH = struct();
            GH.Point = Point;
            GH.VoltageCase = VoltageCase;
            GH.IL1 = IL1;
            GH.aN  = aN;
            GH.u   = u;
            GH.Characteristic = H;
            FixedOrders = [2 3 4 6 8 9];
            FixedCoeff = [
                0.3
                0.4
                0.3
                0.3
                0.2
                0.4];
            Fixed = zeros(6,5);
            for m = 1:length(FixedOrders)
                h = FixedOrders(m);
                I = IL1 * FixedCoeff(m)/100;
                Fixed(m,:) = [
                    h ...
                    FixedCoeff(m) ...
                    I ...
                    FixedCoeff(m) ...
                    h*DimInput.fL];
            end
            GH.Fixed = Fixed;
            %% =====================================================
            % ABB Sidebands
            %% =====================================================
            Speed = netzMatrixTable.Data{r,3};
            fM = Speed * DimInput.PolePairs / 60;
            isTrapez = ...
                strcmp(Point,'BaseSpeed') || ...
                strcmp(Point,'MaxSpeed');
            Sidebands = struct([]);
            rowSB = 0;
            %% Fundamental sideband fL ± 6fM
            I5source = H(1,3);   % Order 5 source harmonic
            rowSB = rowSB + 1;
            Sidebands(rowSB).Point = Point;
            Sidebands(rowSB).VoltageCase = VoltageCase;
            Sidebands(rowSB).Order = 1;
            if isTrapez
                Isb = 0.50 * I5source;
            else
                Isb = 0.40 * I5source;
            end
            Sidebands(rowSB).HarmonicA = I5source;
            Sidebands(rowSB).HarmonicPct = ...
                100 * I5source / IL1;
            Sidebands(rowSB).CurrentA = Isb;
            Sidebands(rowSB).CurrentPct = ...
                100 * Isb / IL1;
            Sidebands(rowSB).FreqMinus = ...
                DimInput.fL - 6*fM;
            Sidebands(rowSB).FreqPlus = ...
                DimInput.fL + 6*fM;
            for k = 1:size(H,1)
                h  = H(k,1);
                Ih = H(k,3);
                fh = H(k,5);
                if isTrapez
                    HarmonicA = 0.60 * Ih;
                    SidebandA = 0.25 * Ih;
                else
                    HarmonicA = 0.25 * Ih;
                    SidebandA = 0.50 * Ih;
                end
                rowSB = rowSB + 1;
                Sidebands(rowSB).Point = Point;
                Sidebands(rowSB).VoltageCase = VoltageCase;
                Sidebands(rowSB).Order = h;
                Sidebands(rowSB).HarmonicA = HarmonicA;
                Sidebands(rowSB).HarmonicPct = ...
                    100 * HarmonicA / IL1;
                Sidebands(rowSB).CurrentA = SidebandA;
                Sidebands(rowSB).CurrentPct = ...
                    100 * SidebandA / IL1;
                Sidebands(rowSB).FreqMinus = ...
                    fh - 6*fM;
                Sidebands(rowSB).FreqPlus = ...
                    fh + 6*fM;
            end
            for k = 1:size(Fixed,1)
                h  = Fixed(k,1);
                Ih = Fixed(k,3);
                fh = Fixed(k,5);
                if isTrapez
                    HarmonicA = 0.60 * Ih;
                    SidebandA = 0.25 * Ih;
                else
                    HarmonicA = 0.25 * Ih;
                    SidebandA = 0.50 * Ih;
                end
                rowSB = rowSB + 1;
                Sidebands(rowSB).Point = Point;
                Sidebands(rowSB).VoltageCase = VoltageCase;
                Sidebands(rowSB).Order = h;
                Sidebands(rowSB).HarmonicA = HarmonicA;
                Sidebands(rowSB).HarmonicPct = ...
                    100 * HarmonicA / IL1;
                Sidebands(rowSB).CurrentA = SidebandA;
                Sidebands(rowSB).CurrentPct = ...
                    100 * SidebandA / IL1;
                Sidebands(rowSB).FreqMinus = ...
                    fh - 6*fM;
                Sidebands(rowSB).FreqPlus = ...
                    fh + 6*fM;
            end
            GH.Sidebands = Sidebands;
            [~,idxSort] = sort([Sidebands.Order]);
            GH.Sidebands = Sidebands(idxSort);
            %% =====================================================
            % ABB Report Data
            %% =====================================================
            GH.Report.Point = Point;
            GH.Report.VoltageCase = VoltageCase;
            GH.Report.IL1 = IL1;
            GH.Report.fM = fM;
            GH.Report.fL = DimInput.fL;
            GH.Report.Fixed = GH.Fixed;
            GH.Report.Harmonics = GH.Characteristic;
            GH.Report.Sidebands = GH.Sidebands;
            GH.Report.ku25 = ku25;
            GH.Report.kuTot = kuTot;
            GridHarmonicObjects{r} = GH;
            GridResult(r,:) = {
                Point
                VoltageCase
                ku25
                kuTot
                H(1,2)
                H(1,3)
                H(2,2)
                H(2,3)
                H(3,2)
                H(3,3)
                H(4,2)
                H(4,3)
                };
        end
        % =========================================================
        % Summary Table
        % =========================================================
        gridHarmonicTable.ColumnName = {
            'Point'
            'VoltageCase'
            'ku25 [%]'
            'kuTot [%]'
            'H5 [%]'
            'H5 [A]'
            'H7 [%]'
            'H7 [A]'
            'H11 [%]'
            'H11 [A]'
            'H13 [%]'
            'H13 [A]'
