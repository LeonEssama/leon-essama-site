            tg.SelectedTab = tabCooling;
        catch ME
            uialert(fig,...
                sprintf('Line %d\n%s', ...
                ME.stack(1).line,...
                ME.message),...
                'Cooling Error');
        end
    end
    function runOperatingPoint(~,~)
        try
            if isempty(DimensioningObjects)
                uialert( ...
                    fig,...
                    'Run Dimensioning first.',...
                    'Warning');
                return
            end
            choice = questdlg( ...
                'Select network case', ...
                'Operating Point', ...
                'SCmin', ...
                'SCmax', ...
                'SCmin');
            if isempty(choice)
                return
            end
            %% ===================================================
            % Find latest matching dimensioning
            %% ===================================================
            DesignFound = false;
            for k = numel(DimensioningObjects):-1:1
                if strcmp( ...
                        DimensioningObjects{k}.Case,...
                        choice)
                    D = DimensioningObjects{k};
                    DesignFound = true;
                    break
                end
            end
            if ~DesignFound
                uialert( ...
                    fig,...
                    ['No ' choice ' dimensioning available.'],...
                    'Warning');
                return
            end
            %% ===================================================
            % Base input
            %% ===================================================
            Input = D.Input;
            Input.u_r = D.Result.u_r;
            Input.exT = D.Result.exT;
            %% ===================================================
            % ABB Operating Point Voltages
            %% ===================================================
            uLmin = Input.u_L;
            uLnom = 1.0;
            uLmax = 1 + (1-uLmin);
            %% RMS operating point
            IMnom = Input.IM;
            I1Snom = D.Result.I1S_nom;
            %% Peak operating point
            IMH = D.Result.IM_start;
            I1SH = D.Result.I1S_start;
            %% ===================================================
            % Study container
            %% ===================================================
            Study = {};
            %% ===================================================
            % CASE 1
            % RMS uLmin
            %% ===================================================
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLmin;
            Case.IM_used = IMnom;
            Case.I1S_used = I1Snom;
            Study{1} = calculate(Case);
            %% ===================================================
            % CASE 2
            % RMS 1.0
            %% ===================================================
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLnom;
            Case.IM_used = IMnom;
            Case.I1S_used = I1Snom;
            Study{2} = calculate(Case);
            %% ===================================================
            % CASE 3
            % RMS uLmax
            %% ===================================================
            Case = Input;
            Case.Mode = 'rms';
            Case.uL_used = uLmax;
            Case.IM_used = IMnom;
            Case.I1S_used = I1Snom;
            Study{3} = calculate(Case);
            %% ===================================================
            % CASE 4
            % PEAK uLmin
            %% ===================================================
            Case = Input;
            Case.Mode = 'peak';
            Case.uL_used = uLmin;
            Case.IM_used = IMH;
            Case.I1S_used = I1SH;
            Study{4} = calculate(Case);
            %% ===================================================
            % CASE 5
            % PEAK 1.0
            %% ===================================================
            Case = Input;
            Case.Mode = 'peak';
            Case.uL_used = 1.0;
            Case.IM_used = IMH;
            Case.I1S_used = I1SH;
            Study{5} = calculate(Case);
            %% ===================================================
            % Store study
            %% ===================================================
            if strcmp(choice,'SCmin')
                OperatingPointStudySCmin = Study;
            else
                OperatingPointStudySCmax = Study;
            end
            %% ===================================================
            % Temporary cache
            %% ===================================================
            DesignDataCache.OperatingPoint = Study;
            assignin( ...
                'base', ...
                'CycloToolDesignDataCache', ...
                DesignDataCache);
            refreshOperatingPointMatrix();
            uialert( ...
                fig,...
                sprintf( ...
                '%s operating point study completed.', ...
                choice),...
                'Operating Point');
        catch ME
            uialert( ...
                fig,...
                ME.message,...
                'Operating Point Error');
        end
    end
