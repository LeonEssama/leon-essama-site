    function validateReportCache()
        %VALIDATEREPORTCACHE
        % Confirm that all required calculations are complete before
        % Design Data report generation.

        requiredCacheSections = { ...
            'Project', ...
            'Input', ...
            'Dimensioning', ...
            'OperatingPoint', ...
            'Harmonics', ...
            'Characteristic', ...
            'FiringAngle', ...
            'Excitation', ...
            'Cooling', ...
            'Protection', ...
            'DetailedSimulation'};

        missingSectionMask = ...
            false( ...
            numel(requiredCacheSections), ...
            1);

        for sectionIndex = 1:numel(requiredCacheSections)

            sectionName = ...
                requiredCacheSections{sectionIndex};

            missingSectionMask(sectionIndex) = ...
                ~isfield(DesignDataCache, sectionName) || ...
                isempty(DesignDataCache.(sectionName));

        end

        missingSections = ...
            string( ...
            requiredCacheSections( ...
            missingSectionMask));

        missingSections = ...
            missingSections(:);

        if ~isempty(missingSections)

            missingSectionText = ...
                strjoin( ...
                "• " + missingSections, ...
                newline);

            error( ...
                'Cyclo:IncompleteReportCache', ...
                ['Complete the following calculations before ', ...
                'generating the Design Data report:', ...
                newline, ...
                newline, ...
                '%s'], ...
                char(missingSectionText));

        end

        %% ---------------------------------------------------------
        % Staleness check: has an input changed since Dimensioning
        % was last run, without Dimensioning (and everything
        % downstream of it) being re-run?
        %% ---------------------------------------------------------

        if isfield(DesignDataCache,'Meta') && ...
                isfield(DesignDataCache.Meta,'DimensioningInputHash')

            idx = find(strcmp({DB.Type},thyDropdown.Value),1);
            currentHash = inputSnapshotHash(buildInput(DB(idx)));

            staleInputs = ...
                ~isempty(currentHash) && ...
                ~strcmp(currentHash, DesignDataCache.Meta.DimensioningInputHash);

            if staleInputs

                error( ...
                    'Cyclo:StaleReportCache', ...
                    ['One or more inputs have changed since Dimensioning ', ...
                    'was last run. Re-run Dimensioning (and every stage ', ...
                    'downstream of it that you use) before generating ', ...
                    'the Design Data report -- otherwise the report would ', ...
                    'silently mix results from different input sets.']);

            end

        end

    end
    function folderName = sanitizeProjectFolderName(projectName)
        %SANITIZEPROJECTFOLDERNAME
        % Convert a project name into a valid output-folder name.

        folderName = ...
            string(projectName);

        invalidCharacters = ...
            ["<", ">", ":", """", "/", "\", "|", "?", "*"];

        for characterIndex = 1:numel(invalidCharacters)

            folderName = ...
                replace( ...
                folderName, ...
                invalidCharacters(characterIndex), ...
                "_");

        end

        folderName = ...
            strtrim(folderName);

        folderName = ...
            regexprep( ...
            folderName, ...
            '\s+', ...
            '_');

        folderName = ...
            regexprep( ...
            folderName, ...
            '_+', ...
            '_');

        folderName = ...
            strip( ...
            folderName, ...
            '_');

        if strlength(folderName) == 0

            folderName = ...
                "CycloTool_Project";

        end

    end
