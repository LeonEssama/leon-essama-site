            HInput = D.Input;
            if strcmp(choice,'SCmin')
                HInput.SCact = HInput.SC_min;
            else
                HInput.SCact = HInput.SC_max;
            end
            if strcmp(choice,'SCmin')
                OPStudy = OperatingPointStudySCmin;
            else
                OPStudy = OperatingPointStudySCmax;
            end
